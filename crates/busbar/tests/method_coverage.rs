#[test]
fn the_matrix_is_a_matrix_and_not_a_list() {
    let (doc, cells) = inventory();

    assert!(
        cells.len() >= MIN_CELLS,
        "only {} cells in qa/method-inventory.json. This gate refuses to pass vacuously — a \
         derivation that reads nothing would report full coverage of nothing. Regenerate with \
         `scripts/method-inventory.py --write`.",
        cells.len()
    );

    let mcp = cells.iter().filter(|c| c.protocol == "mcp").count();
    let a2a = cells.iter().filter(|c| c.protocol == "a2a").count();
    assert!(mcp > 0 && a2a > 0, "both protocols must be in the matrix");
    assert!(
        doc["counts"]["mcp_methods"].as_u64().unwrap_or(0) >= MIN_MCP_METHODS as u64,
        "the MCP method count collapsed; rmcp's model was parsed but yielded almost nothing"
    );
    assert!(
        doc["counts"]["a2a_methods"].as_u64().unwrap_or(0) >= MIN_A2A_METHODS as u64,
        "the A2A method count collapsed; a2a.proto's service block was parsed but yielded almost \
         nothing"
    );

    // Both directions, on both protocols. "Bidirectional in both directions" is the owner's
    // phrase and this is what makes it checkable rather than asserted.
    for protocol in ["mcp", "a2a"] {
        for role in ["server", "client"] {
            assert!(
                cells
                    .iter()
                    .any(|c| c.protocol == protocol && c.role == role),
                "{protocol} has no cell with busbar in the {role} role"
            );
        }
    }

    // Every transport the specifications define is a column, and a real one.
    for (protocol, transport) in [
        ("mcp", "streamable-http"),
        ("mcp", "stdio"),
        ("a2a", "jsonrpc"),
        ("a2a", "http+json"),
        ("a2a", "grpc"),
    ] {
        assert!(
            cells
                .iter()
                .any(|c| c.protocol == protocol && c.transport == transport),
            "{protocol} has no {transport} column. Transport is a real third axis (goal D8), not a \
             deployment detail."
        );
    }

    // Every method appears in BOTH roles on every transport it supports. A method implemented in
    // one direction is still a missing letter, and the matrix must be able to say so.
    let mut seen: BTreeMap<(String, String, String), BTreeSet<String>> = BTreeMap::new();
    for c in &cells {
        seen.entry((c.protocol.clone(), c.method.clone(), c.transport.clone()))
            .or_default()
            .insert(c.role.clone());
    }
    for (key, roles) in &seen {
        assert_eq!(
            roles.len(),
            2,
            "{key:?} exists in only one direction ({roles:?}). Both roles are cells; one of them \
             being absent is precisely the silent omission this gate exists to catch."
        );
    }

    // The obligation is derived, never guessed: busbar HANDLES what the peer originates and
    // ISSUES what it originates itself.
    for c in &cells {
        assert!(
            c.obligation == "handle" || c.obligation == "issue",
            "{}: obligation must be `handle` or `issue`, got {:?}",
            c.id,
            c.obligation
        );
    }
}

#[test]
fn every_na_cell_says_why_it_is_na() {
    let (_, cells) = inventory();
    let na: Vec<&Cell> = cells.iter().filter(|c| c.na_reason.is_some()).collect();
    assert!(
        !na.is_empty(),
        "no N/A cells at all. Some cells ARE legitimately N/A (A2A push delivery has no JSON-RPC \
         or gRPC form; the well-known Agent Card is not an rpc; stdio has no session verbs). Zero \
         of them means the derivation stopped recording the distinction."
    );
    for c in na {
        let reason = c.na_reason.as_deref().unwrap_or("");
        assert!(
            reason.trim().len() >= 20,
            "{} is marked N/A with reason {reason:?}. Mark N/A WITH A REASON — an unexplained \
             absent cell is indistinguishable from an oversight, which is the failure mode.",
            c.id
        );
    }
}

#[test]
fn no_status_entry_is_stale() {
    let (_, cells) = inventory();
    let ids: BTreeSet<&str> = cells.iter().map(|c| c.id.as_str()).collect();
    let claims = status();
    let stale: Vec<&String> = claims
        .keys()
        .filter(|k| !ids.contains(k.as_str()))
        .collect();
    assert!(
        stale.is_empty(),
        "qa/method-coverage.status claims cells that are not in the inventory: {stale:#?}\n\
         A stale entry excuses nothing and hides that the method it named was renamed or removed \
         upstream. Delete it, or fix the id."
    );
}

