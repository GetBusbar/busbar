//! THE COVERAGE GATE. Every cell of `method x direction x transport`, for MCP and A2A, is either
//! `implemented`, `waived(reason, date)`, or **MISSING — and MISSING fails the build**.
//!
//! Owner's ruling, 2026-08-12, and it is the whole reason this file exists:
//!
//! > *"i want a customer to be able to do anything mcp says it can do and anything a2a says it
//! > can do. so if thats calling 20 methods we need to support it. how internally though doesnt
//! > matter. i want full alphabet coverage not just A-J. I want A-Z"*
//!
//! ## Why a test and not a document
//!
//! A document that says "these are the methods" is a claim. It is written from knowledge of the
//! specification, which is exactly how a list ends at J with nobody noticing — the author writes
//! down what they were thinking about, and what they were not thinking about is simply absent.
//! An absent row and a considered-and-inapplicable row look identical on the page.
//!
//! So the three inputs are all files, and none of them is prose:
//!
//! | file | what it is | who writes it |
//! |---|---|---|
//! | `qa/method-inventory.json` | the matrix | GENERATED by `scripts/method-inventory.py` out of rmcp 3.1.2's `model.rs` and a2a-pb 0.2.0's vendored `a2a.proto` |
//! | `qa/method-coverage.status` | the `implemented` / `waived` claims | a human, one line per cell, dated reasons on waivers |
//! | `qa/method-coverage.missing` | the pinned MISSING set | a human, deliberately, by reading a diff |
//!
//! ## Coverage is a MATRIX, not a list
//!
//! A method implemented in one direction is still a missing letter. Two axes beyond the method:
//!
//! - **direction** — busbar as **server** (it is asked) and busbar as **client** (it asks).
//!   busbar is BOTH on BOTH protocols; that is the architectural point, not an aspiration. Each
//!   cell carries the `obligation` the combination implies: `handle` when the peer originates,
//!   `issue` when busbar does.
//! - **transport** — MCP: streamable-HTTP, stdio. A2A: JSON-RPC, HTTP+JSON, gRPC.
//!
//! An N/A cell (`na_reason` in the inventory) is not owed an implementation, and the reason is
//! asserted non-empty below. **An unexplained absent cell is the failure mode this whole gate
//! exists to prevent**, so there is no way to express one.
//!
//! ## Why it is RED today, and why that is the deliverable
//!
//! `crates/busbar/src/mcp/` and `crates/busbar/src/a2a/` are deleted whole in step 15 of the
//! 1.6.0 sequence and rebuilt cell by cell. Claiming a cell on the strength of code scheduled for
//! deletion would be claiming coverage the release does not have. So every cell is MISSING and
//! `qa/method-coverage.missing` pins all of them.
//!
//! The repo's own convention for a deliberately-red gate is the one
//! `testing/a2a-tck/check-baseline.py` states: *"a suite whose result is UNCHANGING is still a
//! gate, because the thing a gate has to catch is a CHANGE."* So the red is pinned rather than
//! ignored, and [`pinned_missing_set_is_exact`] runs on every `cargo test` and fails in BOTH
//! directions — a regression into MISSING is red, and so is an implemented cell whose line was
//! not deleted from the queue. The full-strength 1.6.0 acceptance assertion,
//! [`every_cell_is_implemented_or_waived`], is kept at full strength and marked `#[ignore]` with
//! its reason; CI runs it with `-- --ignored` and it is acceptance test 5 of the release.
//!
//! **Never weaken this gate to make it green.** The MISSING list is the work queue.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

/// Floors. A gate that discovers nothing passes everything. These are sized well below today's
/// real numbers (230 cells, 38 MCP rows, 13 A2A rows) so an ordinary addition does not trip them,
/// and well above zero so a parser that silently reads nothing cannot report success.
const MIN_CELLS: usize = 200;
const MIN_MCP_METHODS: usize = 30;
const MIN_A2A_METHODS: usize = 11;

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("the repository root must exist")
}

fn read(rel: &str) -> String {
    let p = repo_root().join(rel);
    std::fs::read_to_string(&p).unwrap_or_else(|e| panic!("cannot read {}: {e}", p.display()))
}

#[derive(Debug, Clone)]
struct Cell {
    id: String,
    protocol: String,
    method: String,
    role: String,
    transport: String,
    obligation: String,
    na_reason: Option<String>,
}

fn inventory() -> (serde_json::Value, Vec<Cell>) {
    let doc: serde_json::Value = serde_json::from_str(&read("qa/method-inventory.json"))
        .expect("method-inventory.json parses");
    let cells = doc["cells"]
        .as_array()
        .expect("method-inventory.json has a `cells` array")
        .iter()
        .map(|c| Cell {
            id: c["id"].as_str().expect("cell id").to_string(),
            protocol: c["protocol"].as_str().expect("cell protocol").to_string(),
            method: c["method"].as_str().expect("cell method").to_string(),
            role: c["role"].as_str().expect("cell role").to_string(),
            transport: c["transport"].as_str().expect("cell transport").to_string(),
            obligation: c["obligation"]
                .as_str()
                .expect("cell obligation")
                .to_string(),
            na_reason: c["na_reason"].as_str().map(str::to_string),
        })
        .collect();
    (doc, cells)
}

/// What a line in `qa/method-coverage.status` claims.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Claim {
    Implemented,
    Waived { date: String, reason: String },
}

/// Parse the status file. Kept separate from the file read so
/// [`status_parser_refuses_the_three_ways_a_waiver_lies`] can drive it with synthetic input —
/// the waiver path is proven to work WITHOUT landing a fake waiver in the tree to prove it.
fn parse_status(src: &str) -> Result<BTreeMap<String, Claim>, String> {
    let mut out = BTreeMap::new();
    for (n, raw) in src.lines().enumerate() {
        let line = raw.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let (id, rest) = line.split_once('=').ok_or_else(|| {
            format!(
                "line {}: expected `<cell-id> = <state>`, got {raw:?}",
                n + 1
            )
        })?;
        let id = id.trim();
        let rest = rest.trim();
        if id.contains('*') || id.contains('?') {
            return Err(format!(
                "line {}: `{id}` contains a wildcard. EXACT cell ids only — a glob waiver is how a \
                 whole transport disappears in one line.",
                n + 1
            ));
        }
        let claim = if rest == "implemented" {
            Claim::Implemented
        } else if let Some(tail) = rest.strip_prefix("waived") {
            let tail = tail.trim();
            let (date, reason) = tail.split_once(char::is_whitespace).unwrap_or((tail, ""));
            let date_ok = date.len() == 10
                && date.as_bytes()[4] == b'-'
                && date.as_bytes()[7] == b'-'
                && date.bytes().filter(u8::is_ascii_digit).count() == 8;
            if !date_ok {
                return Err(format!(
                    "line {}: a waiver must name the date it was taken, as YYYY-MM-DD. Got {date:?}",
                    n + 1
                ));
            }
            if reason.trim().is_empty() {
                return Err(format!(
                    "line {}: a waiver without a reason is a deletion with extra steps. Say what a \
                     customer loses and why that is acceptable.",
                    n + 1
                ));
            }
            Claim::Waived {
                date: date.to_string(),
                reason: reason.trim().to_string(),
            }
        } else {
            return Err(format!(
                "line {}: unknown state {rest:?}. A cell is `implemented`, `waived <YYYY-MM-DD> \
                 <reason>`, or absent (MISSING).",
                n + 1
            ));
        };
        if out.insert(id.to_string(), claim).is_some() {
            return Err(format!("line {}: `{id}` is claimed twice", n + 1));
        }
    }
    Ok(out)
}

fn status() -> BTreeMap<String, Claim> {
    parse_status(&read("qa/method-coverage.status")).unwrap_or_else(|e| panic!("{e}"))
}

/// The cells owed an implementation that do not have one.
fn missing(cells: &[Cell], claims: &BTreeMap<String, Claim>) -> Vec<Cell> {
    cells
        .iter()
        .filter(|c| c.na_reason.is_none() && !claims.contains_key(&c.id))
        .cloned()
        .collect()
}

fn pinned_missing() -> BTreeSet<String> {
    read("qa/method-coverage.missing")
        .lines()
        .map(|l| l.split('#').next().unwrap_or("").trim().to_string())
        .filter(|l| !l.is_empty())
        .collect()
}

