/// **Acceptance test 5 of the 1.6.0 release** (`GOAL-1.6.0-UNATTENDED.md` §1.1): *"THE COVERAGE
/// GATE IS GREEN — every cell of method × direction × transport."*
///
/// `#[ignore]`d rather than deleted, and rather than softened. It is RED today because the MCP and
/// A2A modules are being deleted and rebuilt, so 210 of 230 cells are still owed. That is the
/// correct state while the rebuild runs: the failure message below IS the release's work queue, and
/// it is printed in full rather than truncated, because a `tail` of a work queue is how the last
/// item gets lost.
///
/// The count in the `#[ignore]` reason MOVES as cells land, and it is not decoration: it is the one
/// place a reader of `cargo test` output sees the queue shrink. The A2A plane's HTTP+JSON binding
/// took the first ten off it.
///
/// Run it: `cargo test -p busbar --test method_coverage -- --ignored`
/// Remove the `#[ignore]` when it passes. Do not remove it any other way.
#[test]
#[ignore = "RED BY DESIGN until 1.6.0: as of 2026-08-12, 210 of 230 cells are MISSING because \
            crates/busbar/src/{mcp,a2a}/ are being deleted and rebuilt cell by cell. The current \
            list is pinned in qa/method-coverage.missing and is the release's work queue. Run with \
            --ignored; do not weaken this test to make it green."]
fn every_cell_is_implemented_or_waived() {
    let (_, cells) = inventory();
    let claims = status();
    let gaps = missing(&cells, &claims);

    if gaps.is_empty() {
        return;
    }

    let mut report = String::new();
    report.push_str(&format!(
        "\n{} of {} cells are MISSING — neither implemented nor waived.\n\
         Every one is a thing the specification says a customer can do and busbar cannot.\n\n",
        gaps.len(),
        cells.len()
    ));
    let mut by_protocol: BTreeMap<&str, Vec<&Cell>> = BTreeMap::new();
    for c in &gaps {
        by_protocol.entry(c.protocol.as_str()).or_default().push(c);
    }
    for (protocol, list) in by_protocol {
        report.push_str(&format!(
            "== {} ({} cells)\n",
            protocol.to_uppercase(),
            list.len()
        ));
        for c in list {
            report.push_str(&format!(
                "  {:<16} busbar-as-{:<6} must {:<6} {}\n",
                c.transport, c.role, c.obligation, c.method
            ));
        }
        report.push('\n');
    }
    report.push_str(
        "Fix by implementing the cell, or by adding a dated line with a reason to \
         qa/method-coverage.status. Do not delete rows from qa/method-inventory.json — it is \
         generated from the SDKs and will come straight back.\n",
    );
    panic!("{report}");
}

// ---------------------------------------------------------------------------
// 4. The gate's own self-test: the waiver path is proven to work without landing a fake waiver.
// ---------------------------------------------------------------------------

#[test]
fn status_parser_refuses_the_three_ways_a_waiver_lies() {
    // A glob would retire a whole transport in one line.
    assert!(
        parse_status("mcp|*|server|client|tools/call = implemented").is_err(),
        "a wildcard cell id must be refused"
    );
    // A waiver with no reason is a deletion with extra steps.
    assert!(
        parse_status("mcp|stdio|server|client|ping = waived 2026-08-12").is_err(),
        "a waiver with no reason must be refused"
    );
    // A waiver with no date cannot be aged, reviewed or expired.
    assert!(
        parse_status("mcp|stdio|server|client|ping = waived because reasons").is_err(),
        "a waiver with no date must be refused"
    );
    // And a made-up state is not a fourth state.
    assert!(
        parse_status("mcp|stdio|server|client|ping = partially").is_err(),
        "there are three states and `partially` is not one of them"
    );

    // The two legitimate claims parse, and they are what silences a cell.
    let ok = parse_status(
        "# a comment\n\
         mcp|stdio|server|client|ping = implemented\n\
         \n\
         a2a|grpc|client|client|ListTasks = waived 2026-08-12 the gRPC client leg lands in step 15\n",
    )
    .expect("well-formed claims parse");
    assert_eq!(ok.len(), 2);
    assert_eq!(ok["mcp|stdio|server|client|ping"], Claim::Implemented);
    assert!(matches!(
        &ok["a2a|grpc|client|client|ListTasks"],
        Claim::Waived { date, reason } if date == "2026-08-12" && reason.starts_with("the gRPC")
    ));

    // The gate must move in both directions or it is decorative: a cell with a claim is NOT
    // missing, and the same cell without one IS.
    let (_, cells) = inventory();
    let victim = cells
        .iter()
        .find(|c| c.na_reason.is_none())
        .expect("at least one cell is owed an implementation");
    let empty = BTreeMap::new();
    assert!(
        missing(&cells, &empty).iter().any(|c| c.id == victim.id),
        "with no claims at all, {} must count as MISSING",
        victim.id
    );
    let mut claimed = BTreeMap::new();
    claimed.insert(victim.id.clone(), Claim::Implemented);
    assert!(
        !missing(&cells, &claimed).iter().any(|c| c.id == victim.id),
        "a claimed cell must stop counting as MISSING — otherwise no amount of work could ever \
         turn this gate green and it would be ignored instead of satisfied"
    );
}
