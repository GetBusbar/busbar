//! C-HEADER's static-assert generator (ABI-MIN3-INTERFACE §7.8, §14; owner W1-A13): one `_Static_assert` per
//! struct size and alignment, field offset and constant of `busbar_plugin.h`, each value read from the Rust
//! item it mirrors (`size_of`, `align_of`, `offset_of!`, the consts, `CORE_FP` and `secret::FP`). Compiled with
//! the header, any drift on either side is a compile error until both move in one MR.
//!
//! Hold (W1-A13 follow-up): `bb_host`'s fn fields, `bb_plugin`'s five entries and `former_names`, and
//! `bb_secret_vt` have no Rust field yet (UNSAFE-MIN: they land with W1-A2, W1-A4 and busbar-ffi). Until then
//! they are asserted against their frozen §5/§7.1/§8.2 order in pointer words; each moves to `offset_of!` on
//! the Rust field when it lands.

use core::mem::{align_of, offset_of, size_of};
use std::fmt::Write as _;

use busbar_plugin_abi as abi;

use abi::fail::{failed, refused, FAIL_TEXT_WIRE_MAX};
use abi::host::{level, CryptoReq, CryptoRet, DeploymentId};
use abi::plugin::OPEN_DRY_RUN;
use abi::records::{tag, EndpointRec, FailRec, InstanceRec, MaskRec, RecHead, U32Rec};
use abi::stamp::Stamp;
use abi::types::{Bytes, KindCode, RawOut, Status, Str, Token};
use abi::versions::{self, EngineVersion};

/// The whole assert file: `#include "busbar_plugin.h"`, then one `_Static_assert` per line.
pub fn generate() -> String {
    let mut c = String::from(
        "/* Generated by C-HEADER (busbar-plugin-abi/tests/c_header/asserts.rs); never edited. */\n\
         #include <stddef.h>\n#include \"busbar_plugin.h\"\n",
    );
    let mut eq = |what: &str, value: u64| {
        writeln!(c, "_Static_assert(({what}) == {value}ull, \"{what}\");").expect("a String");
    };
    let word = size_of::<usize>() as u64;

    macro_rules! layout {
        ($c:literal = $rust:ty { $($cf:ident = $rf:tt),* }) => {
            eq(concat!("sizeof(", $c, ")"), size_of::<$rust>() as u64);
            eq(concat!("_Alignof(", $c, ")"), align_of::<$rust>() as u64);
            $(eq(concat!("offsetof(", $c, ", ", stringify!($cf), ")"), offset_of!($rust, $rf) as u64);)*
        };
    }
    layout!("bb_bytes" = Bytes<'static> {});
    layout!("bb_str" = Str<'static> {});
    layout!("bb_raw_out" = RawOut {});
    eq(
        "offsetof(bb_raw_out, ptr)",
        abi::types::RAW_OUT_PTR_AT as u64,
    );
    eq(
        "offsetof(bb_raw_out, len)",
        abi::types::RAW_OUT_LEN_AT as u64,
    );
    eq(
        "offsetof(bb_raw_out, cap)",
        abi::types::RAW_OUT_CAP_AT as u64,
    );
    layout!("bb_status" = Status {});
    layout!("bb_token" = Token {});
    layout!("bb_crypto_req" = CryptoReq<'static> {
        alg = alg, key_form = key_form, param = param, key = key, data = data, aux = aux, aad = aad
    });
    layout!("bb_crypto_ret" = CryptoRet { status = status, _r = _r, out = out });
    layout!("bb_deployment_id" = DeploymentId { bytes = 0 });
    layout!("bb_rec_head" = RecHead { tag = tag, _r = _r, len = len });
    layout!("bb_fail_rec" = FailRec { status = status, code = code });
    layout!("bb_instance_rec" = InstanceRec { inst = inst });
    layout!("bb_mask_rec" = MaskRec { mask = mask });
    layout!("bb_u32_rec" = U32Rec { value = value, _r = _r });
    layout!("bb_endpoint_rec" = EndpointRec { op = op, flags = flags });
    layout!("bb_engine_version" = EngineVersion {
        major = major, minor = minor, patch = patch, _reserved = _reserved
    });
    layout!("bb_stamp" = Stamp {
        magic = magic, format = format, size = size, kind = kind, kind_abi = kind_abi,
        mechanism = mechanism, flags = flags, layout = layout, mechanism_layout = mechanism_layout,
        semantic = semantic, mechanism_semantic = mechanism_semantic, engine_min = engine_min,
        engine_max = engine_max, name = name, version = version, target = target, build_id = build_id,
        crypto = crypto, _reserved = _reserved
    });
    eq(
        "offsetof(bb_plugin, stamp)",
        abi::plugin::PLUGIN_STAMP_AT as u64,
    );
    eq(
        "offsetof(bb_plugin, kind_vt)",
        abi::plugin::PLUGIN_KIND_VT_AT as u64,
    );
    // The hold above: the frozen order, in pointer words.
    let host = [
        "ctx",
        "now",
        "mono",
        "random",
        "crypto",
        "log",
        "log_level",
        "grow",
        "deployment",
        "migrate_admit",
    ];
    for (i, field) in host.iter().enumerate() {
        eq(&format!("offsetof(bb_host, {field})"), i as u64 * word);
    }
    eq("sizeof(bb_host)", 10 * word);
    let entries = [
        "describe",
        "open",
        "resume",
        "cancel",
        "close",
        "former_names",
    ];
    for (i, field) in entries.iter().enumerate() {
        eq(
            &format!("offsetof(bb_plugin, {field})"),
            (i as u64 + 2) * word,
        );
    }
    eq("sizeof(bb_plugin)", 9 * word);
    eq("offsetof(bb_secret_vt, resolve)", 0);
    eq("sizeof(bb_secret_vt)", word);

    // Constants.
    eq("BB_MECHANISM", versions::MECHANISM.into());
    eq("BB_SECRET_ABI", versions::SECRET.into());
    eq("BB_SECRET_ABI", abi::secret::ABI.into());
    eq("BB_KIND_SECRET", KindCode::Secret as u64);
    eq("BB_CORE_FP", abi::fp::CORE_FP);
    eq("BB_SECRET_FP", abi::secret::FP);
    for (name, s) in [
        ("BB_OK", Status::OK),
        ("BB_REFUSED", Status::REFUSED),
        ("BB_FAILED", Status::FAILED),
        ("BB_NEED", Status::NEED),
        ("BB_FAULT", Status::FAULT),
    ] {
        eq(name, s.0.into());
    }
    for (name, v) in [
        ("BB_LOG_ERROR", level::ERROR),
        ("BB_LOG_WARN", level::WARN),
        ("BB_LOG_INFO", level::INFO),
        ("BB_LOG_DEBUG", level::DEBUG),
        ("BB_LOG_TRACE", level::TRACE),
        ("BB_R_UNSUPPORTED", refused::R_UNSUPPORTED),
        ("BB_R_INVALID", refused::R_INVALID),
        ("BB_R_NOT_FOUND", refused::R_NOT_FOUND),
        ("BB_R_DENIED", refused::R_DENIED),
        ("BB_R_CONFIG", refused::R_CONFIG),
        ("BB_R_VERSION", refused::R_VERSION),
        ("BB_F_INTERNAL", failed::F_INTERNAL),
        ("BB_OPEN_DRY_RUN", OPEN_DRY_RUN),
    ] {
        eq(name, v.into());
    }
    for (name, t) in [
        ("BB_TAG_TEXT", tag::TEXT),
        ("BB_TAG_FAIL", tag::FAIL),
        ("BB_TAG_INSTANCE", tag::INSTANCE),
        ("BB_TAG_CONFIG", tag::CONFIG),
        ("BB_TAG_ERROR", tag::ERROR),
        ("BB_TAG_D_METHODS", tag::D_METHODS),
        ("BB_TAG_D_SCHEMA", tag::D_SCHEMA),
        ("BB_TAG_D_ERRORS", tag::D_ERRORS),
        ("BB_TAG_ENDPOINT", tag::ENDPOINT),
        ("BB_TAG_SECRET_VALUE", abi::secret::tag::VALUE),
        ("BB_TAG_SECRET_D_REF_SCHEMA", abi::secret::tag::D_REF_SCHEMA),
    ] {
        eq(name, t.into());
    }
    eq("BB_FAIL_TEXT_WIRE_MAX", FAIL_TEXT_WIRE_MAX as u64);
    eq("BB_SECRET_REQUIRED", abi::secret::M_RESOLVE);
    c
}
