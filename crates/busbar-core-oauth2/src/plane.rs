/// The store this plane runs on: [`oauth_as::store::MemoryStorage`] behind the ONE changed read that serves Client
/// ID Metadata Documents. See [`super::cimd::CimdStore`].
pub(crate) type AsStore = super::cimd::CimdStore;

/// The concrete server type, named once so the three places that hold it agree by construction
/// rather than by three matching turbofishes.
pub(crate) type AsServer = AuthorizationServer<AsStore, SystemClock>;

/// The HTTP service over [`AsServer`]: `http::Request` in, `http::Response` out, no framework.
pub(crate) type AsService = oauth_as::http::AuthorizationService<AsStore, SystemClock>;

/// EVERYTHING THIS PLANE ALLOCATES. Absent unless `oauth_as:` is configured.
pub(crate) struct AsPlane {
    identity: AsIdentity,
    service: AsService,
    server: Arc<AsServer>,
    /// The consent sessions, shared with the two closures the service was built with. Held here as
    /// well so the consent ROUTE can open a session and stake an approval — the two halves of the
    /// screen are a busbar handler and an `oauth-as` callback, and they have to be looking at the
    /// same table.
    sessions: Arc<super::consent::Sessions>,
    /// The RFC 8414 document the PLAIN posture serves, or `None` under the FAPI 2.0 posture, which
    /// serves `oauth-as`'s own. See [`plain_metadata`].
    plain_metadata: Option<bytes::Bytes>,
    /// The verifiers a DPoP proof at busbar's resource is checked with: the plane's ES256 one.
    dpop_verifiers: oauth_as::jwt::JwsVerifiers,
    /// This server's expired-record sweeper, stopped when the server is let go ([`Sweeper`]).
    /// `None` for a server built without one (a test that drives the store directly).
    sweeper: Option<Sweeper>,
    /// What the next generation carries on from this one.
    carried: Arc<Carried>,
}

/// WHAT A GENERATION HANDS THE NEXT: everything the server holds rather than reads from config.
#[derive(Default)]
pub(crate) struct Carried {
    records: Arc<super::cimd::Records>,
    sessions: Arc<super::consent::Sessions>,
    /// The ephemeral signing key (PKCS#8 DER), generated by the first generation that ran without
    /// `signing_key` and signed with by every later one that runs without it: a reload does not
    /// void the tokens it signed.
    ephemeral_key: std::sync::OnceLock<Vec<u8>>,
    /// The throttle every generation's server asks ([`Throttle`]): one budget across reloads.
    limiter: Arc<oauth_as::FixedWindowRateLimiter>,
    /// The node's registration budget ([`Registrations`]): one across reloads, as the limiter is.
    registrations: Arc<Registrations>,
}

/// THE CARRIED THROTTLE, as one generation's server holds it. `oauth-as` takes its limiter boxed
/// and owns it; this hands each generation the SAME counters, so a config reload never refills a
/// caller's registration, authorization or client-authentication budget.
///
/// Registration is counted by [`Registrations`]; every other attempt by `oauth-as`'s own
/// `FixedWindowRateLimiter`.
struct Throttle {
    limiter: Arc<oauth_as::FixedWindowRateLimiter>,
    registrations: Arc<Registrations>,
}

impl oauth_as::RateLimiter for Throttle {
    fn check(&self, attempt: oauth_as::Attempt<'_>) -> oauth_as::RateLimitDecision {
        if let oauth_as::Attempt::ClientRegistration = attempt {
            return self.registrations.check();
        }
        oauth_as::RateLimiter::check(&*self.limiter, attempt)
    }

    fn record(&self, attempt: oauth_as::Attempt<'_>, outcome: oauth_as::AttemptOutcome) {
        if let oauth_as::Attempt::ClientRegistration = attempt {
            if outcome == oauth_as::AttemptOutcome::Succeeded {
                self.registrations.admitted();
            }
            return;
        }
        oauth_as::RateLimiter::record(&*self.limiter, attempt, outcome);
    }
}

/// How many registrations one node admits in one [`REGISTRATION_WINDOW`]: `oauth-as`'s own
/// derivation (its `rate_limit` module), kept as the node's ceiling.
const REGISTRATIONS_PER_WINDOW: u64 = oauth_as::rate_limit::DEFAULT_CLIENT_REGISTRATION_CAPACITY;

/// The window [`REGISTRATIONS_PER_WINDOW`] is counted over.
const REGISTRATION_WINDOW: std::time::Duration = oauth_as::rate_limit::DEFAULT_WINDOW;

/// THE NODE'S REGISTRATION BUDGET, counted in registrations it ADMITS.
///
/// A registration request names no caller and no client, and this plane is handed no caller
/// address, so the budget is one per node. Charging every ATTEMPT against it, as `oauth-as`'s
/// shipped limiter does (a refused one ten times over), let one unauthenticated caller close
/// registration for everyone: six registrations the policy refuses a minute spent the whole of it.
/// So what the budget counts is what it exists to bound, the clients a registration writes:
///
/// * a registration ADMITTED in this window counts until the window rolls;
/// * a registration being ANSWERED counts while it is answered, so a burst of concurrent requests
///   cannot all pass the check before any of them is admitted;
/// * a registration REFUSED, or a body that does not parse, counts for nothing once its answer is
///   sent. Its work is one bounded parse and one policy check, a request like any other.
///
/// Past [`REGISTRATIONS_PER_WINDOW`] admitted and in flight, a registration is refused until the
/// window rolls.
pub(crate) struct Registrations {
    /// The instant windows are counted from, on the monotonic clock.
    base: std::time::Instant,
    state: std::sync::Mutex<RegistrationWindow>,
}

#[derive(Default)]
struct RegistrationWindow {
    /// Which window `admitted` belongs to.
    index: u64,
    /// Registrations admitted in that window.
    admitted: u64,
    /// Registrations being answered now.
    in_flight: u64,
}

impl Default for Registrations {
    fn default() -> Self {
        Self {
            base: std::time::Instant::now(),
            state: std::sync::Mutex::new(RegistrationWindow::default()),
        }
    }
}

tokio::task_local! {
    /// The registration request this task is answering ([`AsPlane::handle`]), and whether it holds
    /// a share of the budget.
    static REGISTERING: Answering;
}

/// One registration request being answered. Its share of the budget goes back when it is let go,
/// however the request ends: answered, refused, or dropped.
struct Answering {
    budget: Arc<Registrations>,
    held: std::cell::Cell<bool>,
}

impl Drop for Answering {
    fn drop(&mut self) {
        if self.held.get() {
            self.budget.release();
        }
    }
}

impl Registrations {
    /// The window's counters, rolled to the current window.
    fn window(&self) -> std::sync::MutexGuard<'_, RegistrationWindow> {
        let mut w = self
            .state
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        let index = self.base.elapsed().as_secs() / REGISTRATION_WINDOW.as_secs();
        if w.index != index {
            w.index = index;
            w.admitted = 0;
        }
        w
    }

    /// May one more registration be answered? Inside a registration request ([`REGISTERING`]) the
    /// request holds a share until it is let go; outside one (a caller of the server's own method)
    /// the attempt is counted as admitted at once, since nothing would give a share back.
    fn check(&self) -> oauth_as::RateLimitDecision {
        let mut w = self.window();
        if w.admitted + w.in_flight >= REGISTRATIONS_PER_WINDOW {
            return oauth_as::RateLimitDecision::Deny;
        }
        match REGISTERING.try_with(|answering| answering.held.replace(true)) {
            Ok(false) => w.in_flight += 1,
            // This request already holds its share.
            Ok(true) => {}
            Err(_) => w.admitted += 1,
        }
        oauth_as::RateLimitDecision::Allow
    }

    /// A registration was admitted. Counted for the window when a request holds its share; a caller
    /// with no request was counted at its check.
    fn admitted(&self) {
        if REGISTERING.try_with(|_| ()).is_ok() {
            self.window().admitted += 1;
        }
    }

    /// A request let its share go.
    fn release(&self) {
        let mut w = self.window();
        w.in_flight = w.in_flight.saturating_sub(1);
    }
}

impl Carried {
    /// What the FIRST generation holds: the deployment store's records when `store` is reachable,
    /// this process's otherwise.
    pub(crate) fn over(store: Option<Arc<dyn busbar_contract::store_calls::StoreCalls>>) -> Self {
        match store {
            Some(calls) => Self {
                records: Arc::new(super::cimd::Records::shared(Arc::new(
                    super::shared::Shared::new(calls),
                ))),
                ..Self::default()
            },
            None => Self::default(),
        }
    }

    /// The deployment's store, when the records are kept there.
    pub(crate) fn store(&self) -> Option<&Arc<super::shared::Shared>> {
        self.records.store()
    }
}

/// Why the plane could not be built. Distinct from [`super::config::AsCfgError`] because these are
/// failures of the RUNTIME (a key that will not load, an endpoint the library refuses to route)
/// rather than of the grammar, and an operator needs to be able to tell the two apart.
#[derive(Debug)]
pub(crate) enum AsBuildError {
    /// The configured signing key could not be loaded.
    SigningKey(super::signer::KeyError),
    /// The signing key secret reference did not resolve, or did not decode as base64.
    SigningKeyMaterial(String),
    /// `oauth-as` refused to build its service. In practice this is an advertised endpoint that is
    /// not under the issuer, which cannot happen with endpoints this module derives — it is carried
    /// rather than unwrapped because "cannot happen" is not a thing a boot path should assert.
    Service(oauth_as::http::ServiceError),
}

impl std::fmt::Display for AsBuildError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AsBuildError::SigningKey(e) => write!(f, "oauth_as.signing_key: {e}"),
            AsBuildError::SigningKeyMaterial(e) => write!(
                f,
                "oauth_as.signing_key: {e}. It must be a base64-encoded PKCS#8 v1 DER P-256 private \
                 key — what `openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 \
                 -outform DER | base64` produces."
            ),
            AsBuildError::Service(e) => write!(f, "oauth_as: {e}"),
        }
    }
}

impl AsPlane {
    /// Build the plane, holding nothing yet (see [`Self::build_carrying`]): a fixture's server.
    #[cfg(any(test, feature = "test-support"))]
    pub(crate) fn build(
        identity: AsIdentity,
        key_material: Option<&str>,
        protected_resources: Vec<String>,
        fetch: Arc<dyn super::cimd::CimdFetch>,
    ) -> Result<Self, AsBuildError> {
        Self::build_carrying(
            identity,
            key_material,
            protected_resources,
            fetch,
            Arc::default(),
        )
    }

    /// Build the plane for one config generation, only when `oauth_as:` is present, over what the
    /// generation before it held (`carried`).
    ///
    /// `key_material` is the resolved secret, already read from wherever the `SecretRef` pointed;
    /// `None` means the operator configured no key and accepts an ephemeral one. This function does
    /// not resolve secrets itself, so it stays testable without a secret module and so the one
    /// place that reads operator secrets remains the config layer.
    ///
    /// `fetch` is how a Client ID Metadata Document is fetched: [`super::cimd::ConnectorFetch`] over
    /// the root Connector in production.
    pub(crate) fn build_carrying(
        identity: AsIdentity,
        key_material: Option<&str>,
        protected_resources: Vec<String>,
        fetch: Arc<dyn super::cimd::CimdFetch>,
        carried: Arc<Carried>,
    ) -> Result<Self, AsBuildError> {
        let key = match key_material {
            Some(b64) => {
                use base64::Engine as _;
                let der = base64::engine::general_purpose::STANDARD
                    .decode(b64.trim())
                    .map_err(|e| AsBuildError::SigningKeyMaterial(e.to_string()))?;
                RingEs256Key::from_pkcs8_der(identity.key_id(), &der)
                    .map_err(AsBuildError::SigningKey)?
            }
            None => {
                let der = match carried.ephemeral_key.get() {
                    Some(der) => der,
                    None => {
                        // ONE KEY PER DEPLOYMENT: kept in the store and read back by every node and
                        // every generation; only the build that wins the store's minting claim
                        // mints it. Without a store, one per process.
                        let fresh = match carried.store() {
                            Some(store) => super::shared::wait_for(store.signing_key(|| {
                                RingEs256Key::generate_pkcs8().map_err(|e| e.to_string())
                            }))
                            .map_err(AsBuildError::SigningKeyMaterial)?,
                            None => {
                                RingEs256Key::generate_pkcs8().map_err(AsBuildError::SigningKey)?
                            }
                        };
                        carried.ephemeral_key.get_or_init(|| fresh)
                    }
                };
                RingEs256Key::from_pkcs8_der(identity.key_id(), der)
                    .map_err(AsBuildError::SigningKey)?
            }
        };

        let mut config = ServerConfig::new(identity.issuer(), identity.consent_url());
        config.authorization_endpoint = Some(format!("{}/authorize", identity.issuer()));
        config.token_endpoint = Some(format!("{}/token", identity.issuer()));
        config.jwks_uri = Some(identity.jwks_uri());
        config.registration = Some(super::policy::registration_config(&identity));
        config.access_token_ttl = identity.access_token_ttl();
        // A refresh chain ends: rotation keeps its first expiry, so this bounds the whole chain.
        config.refresh_token_ttl = Some(identity.refresh_token_ttl());
        config.scopes_supported =
            (!identity.default_grant().is_empty()).then(|| identity.default_grant().to_vec());
        // RFC 8707 §2: the resources this server is WILLING to mint for. Setting it is not optional
        // hygiene. With `None`, any syntactically valid absolute URI is accepted as a `resource`,
        // and under the JWT profile that requested value REPLACES the audience in the `aud` claim —
        // so any client could obtain a token THIS server signed carrying another resource server's
        // identifier, which that server would then verify against our JWKS and honour. The list is
        // busbar's own planes and nothing else.
        config.allowed_resources = Some(
            protected_resources
                .iter()
                .map(|r| r.as_str().into())
                .collect::<Vec<Box<str>>>()
                .into_boxed_slice(),
        );
        config.protected_resources =
            (!protected_resources.is_empty()).then(|| protected_resources.clone());
        // RFC 9068 `at+jwt`, ES256, signed with `ring`. JWT rather than opaque because the resource
        // half of this deployment must be able to establish the audience binding from the token
        // itself: `auth::audience::inspect_bearer` refuses a bearer whose `aud` it cannot read, and
        // it refuses it on purpose — "I cannot tell whether this was minted for me" has one safe
        // answer. An opaque token would be refused by busbar's own front door.
        //
        // The audience is the FIRST protected resource, and is overridden per request by the
        // RFC 8707 `resource` parameter the client sends; the `allowed_resources` list above is what
        // stops that override naming somebody else.
        let audience = protected_resources
            .first()
            .cloned()
            .unwrap_or_else(|| identity.issuer().to_string());
        config.access_token_format = oauth_as::jwt::AccessTokenFormat::Jwt(Box::new(
            oauth_as::jwt::JwtConfig::new(key, audience).with_jwks_uri(identity.jwks_uri()),
        ));

        // THE FAPI 2.0 SECURITY PROFILE, applied only when the operator wrote `fapi2: true`. Every
        // write below is inside this branch, so the plain posture builds the `ServerConfig` it
        // always built. The authorization code lifetime needs no write: `oauth-as`'s default is
        // already the profile's 60-second ceiling (s5.3.2.1-11).
        if identity.fapi2() {
            config = fapi2_posture(config, &identity);
        }

        // The store: `MemoryStorage` behind the CIMD read. The ceiling handed to it is the SAME
        // `default_grant_scopes` the registration config above is built from, so a client arriving
        // by document and one arriving by registration land under one ceiling by construction.
        let store = super::cimd::CimdStore::over(
            Arc::clone(&carried.records),
            super::policy::default_grant_scopes(&identity),
            fetch,
            provisioned_clients(&identity),
        );
        let server = Arc::new(
            AuthorizationServer::new(config, store)
                // THE ES256 VERIFIER: what checks an RFC 9449 DPoP proof and an RFC 7523
                // `private_key_jwt` assertion. `oauth-as` refuses every signed credential whose
                // algorithm has no verifier, and advertises exactly the algorithms that have one.
                .with_jws_verifier(Arc::new(RingEs256Verifier))
                // PS256, FAPI 2.0 s5.4.1's other algorithm: an RSA-keyed provisioned client's
                // assertions and DPoP proofs. The plain posture's document advertises neither list.
                .with_jws_verifier(Arc::new(RingPs256Verifier))
                .with_registration_policy(Box::new(super::policy::OpenRegistration))
                // THE THROTTLE: registration is open and takes no credential, so it is bounded
                // here, with the authorization endpoint and client authentication (see
                // `super::policy`, "Registration is bounded").
                .with_rate_limiter(Box::new(Throttle {
                    limiter: Arc::clone(&carried.limiter),
                    registrations: Arc::clone(&carried.registrations),
                })),
        );

        let sessions = Arc::clone(&carried.sessions);
        let service = oauth_as::http::ServiceBuilder::new(Arc::clone(&server))
            .with_subject_resolver(super::consent::subject_resolver(Arc::clone(&sessions)))
            .with_approval_resolver(super::consent::approval_resolver(
                Arc::clone(&sessions),
                identity.consent_url(),
            ))
            .build()
            .map_err(AsBuildError::Service)?;
        let plain_metadata = (!identity.fapi2()).then(|| plain_metadata(&server));
        let mut dpop_verifiers = oauth_as::jwt::JwsVerifiers::new();
        dpop_verifiers.install(Arc::new(RingEs256Verifier));
        dpop_verifiers.install(Arc::new(RingPs256Verifier));

        Ok(Self {
            identity,
            service,
            server,
            sessions,
            plain_metadata,
            dpop_verifiers,
            sweeper: None,
            carried,
        })
    }

    /// RFC 9449 s7 at busbar's own protected resource (the kernel door, `auth::dpop`, through the
    /// seam). `true` only when every check holds:
    ///
    /// * the proof verifies for THIS request line: ES256 signature over its own `jwk`, `typ`,
    ///   `htm`, `htu` (this plane's origin + the request path), `iat` within the window (s4.3);
    /// * its `ath` is the SHA-256 of the presented token (s4.3 (11)), which binds it to the token;
    /// * its key's RFC 7638 thumbprint is the token's `cnf.jkt` (s7.1), which binds the token to it;
    /// * its `jti` has not been seen (s11.1), claimed in the plane's replay ledger until the proof
    ///   could no longer pass the `iat` check anyway.
    ///
    /// The token's own signature, issuer and audience are NOT judged here: the chain judges them
    /// next, exactly as it judges a bearer. This is what the token's binding adds, and only that.
    pub(crate) async fn verify_dpop(
        &self,
        presented: busbar_kernel::oauth_as::seam::DpopPresentation,
    ) -> bool {
        use base64::Engine as _;
        use oauth_as::store::Storage as _;
        let htu = format!("{}{}", self.identity.origin(), presented.path);
        let Ok(proof) = oauth_as::dpop::verify_proof(
            &self.dpop_verifiers,
            &presented.proof,
            &presented.method,
            &htu,
            std::time::SystemTime::now(),
        ) else {
            return false;
        };
        let ath = base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(
            ring::digest::digest(&ring::digest::SHA256, presented.token.as_bytes()).as_ref(),
        );
        let ath_matches = oauth_as::jwt::CompactJws::parse(&presented.proof)
            .is_ok_and(|jws| jws.claim_str("ath") == Some(ath.as_str()));
        let bound_to_proof_key =
            oauth_as::jwt::CompactJws::parse(&presented.token).is_ok_and(|jws| {
                jws.payload
                    .get("cnf")
                    .and_then(|cnf| cnf.get("jkt"))
                    .and_then(|jkt| jkt.as_str())
                    == Some(proof.jkt.as_str())
            });
        if !ath_matches || !bound_to_proof_key {
            return false;
        }
        // Namespaced apart from the token endpoint's own proof `jti`s, which share the ledger.
        let replay_id = format!("dpop-resource:{}:{}", proof.jkt, proof.jti);
        matches!(
            self.server
                .store()
                .claim_replay_id(&replay_id, proof.replay_until)
                .await,
            Ok(true)
        )
    }

    /// Answer one request: the plane's whole wire surface. The plain posture's metadata document
    /// is the one answer busbar serves itself ([`plain_metadata`]); every other request is
    /// `oauth-as`'s, unchanged.
    pub(crate) async fn handle<B>(&self, request: http::Request<B>) -> oauth_as::http::Response
    where
        B: axum::body::HttpBody,
    {
        if let Some(document) = &self.plain_metadata {
            if request.method() == http::Method::GET
                && request.uri().path() == self.identity.metadata_path()
            {
                let mut response =
                    http::Response::new(oauth_as::http::Body::from(document.clone()));
                response.headers_mut().insert(
                    http::header::CONTENT_TYPE,
                    http::HeaderValue::from_static("application/json;charset=UTF-8"),
                );
                return response;
            }
        }
        let registering = request.method() == http::Method::POST
            && request.uri().path() == self.identity.register_path();
        self.prepare(Seen::of(&request)).await;
        // Box::pin: the whole `oauth-as` dispatch future (~56 KB monomorphized), boxed at its one
        // call site, as `routes::forward` did before this method existed.
        let answer = Box::pin(self.service.handle(request));
        if !registering {
            return answer.await;
        }
        // A registration request holds its share of the node's budget while it is answered, and
        // gives it back when the answer is sent ([`Registrations`]).
        let answering = Answering {
            budget: Arc::clone(&self.carried.registrations),
            held: std::cell::Cell::new(false),
        };
        REGISTERING.scope(answering, answer).await
    }

    /// The scope an authorization request from `client_id` is granted on approval, as the consent
    /// screen names it. `requested` is the request's `scope`, `None` when it named none.
    ///
    /// RFC 6749 s3.3, as `oauth-as` applies it at the authorization endpoint: a request naming a
    /// scope is granted that set (sorted, deduplicated); one naming none is granted the client's
    /// registered default, trimmed to what the registration allows. That default is the whole
    /// `default_grant` for a provisioned client, and for a metadata-document client whose document
    /// names no scope, so the screen names it rather than saying nothing is asked. A client this
    /// server does not know is granted nothing.
    pub(crate) async fn granted_scope(&self, client_id: &str, requested: Option<&str>) -> String {
        use oauth_as::store::Storage as _;
        if let Some(raw) = requested {
            // A scope that does not parse is refused at the authorization endpoint; the screen
            // names it as it was sent.
            return oauth_as::scope::ScopeSet::parse(raw)
                .map_or_else(|_| raw.to_string(), |set| set.to_string());
        }
        let client = self
            .server
            .store()
            .get_client(&oauth_as::client::ClientId::new(client_id))
            .await;
        match client {
            Ok(Some(client)) => granted_default(&client).to_string(),
            _ => String::new(),
        }
    }

    /// The display summary of a pushed request that has not been redeemed yet. See
    /// [`super::cimd::Pushed`].
    pub(crate) async fn pushed(&self, request_uri: &str) -> Option<super::cimd::Pushed> {
        self.server.store().pushed(request_uri).await
    }

    /// Record that the consent screen showed this pushed request, answering whether it had been
    /// shown before.
    pub(crate) async fn mark_pushed_shown(&self, request_uri: &str) -> bool {
        self.server.store().mark_pushed_shown(request_uri).await
    }

    /// Open a consent session for `subject` under `id`: in this process, and in the deployment's
    /// store when the records are kept there, so the browser's next request may land on any node.
    pub(crate) async fn open_session(&self, subject: &str, id: String) -> String {
        if let Some(store) = self.carried.store() {
            if let Err(e) = store
                .open_session(&id, subject, super::consent::SESSION_TTL)
                .await
            {
                tracing::warn!(error = %e, "oauth_as: the consent session could not be kept");
            }
        }
        self.sessions.open(subject, id)
    }

    /// Stake ONE answer for `key` against session `id`. With the store, the answer is kept there
    /// alone: it is spent by exactly one `/authorize`, on whichever node ([`Self::handle`]).
    pub(crate) async fn stake(&self, id: &str, key: String, approve: bool) {
        match self.carried.store() {
            Some(store) => {
                if let Err(e) = store
                    .stake(id, &key, approve, super::consent::SESSION_TTL)
                    .await
                {
                    tracing::warn!(error = %e, "oauth_as: the consent answer could not be kept");
                }
            }
            None => self.sessions.stake(id, key, approve),
        }
    }

    /// Whether an answer is staked for `key` on session `id`, without spending it.
    pub(crate) async fn is_staked(&self, id: &str, key: &str) -> bool {
        match self.carried.store() {
            Some(store) => store.is_staked(id, key).await.unwrap_or(false),
            None => self.sessions.is_staked(id, key),
        }
    }

    /// With the store: hand the two synchronous consent callbacks what this request needs from it,
    /// before `oauth-as` asks. The session the cookie names is read into this process's table, and on
    /// the authorization endpoint the answer staked for this exact request is SPENT in the store (one
    /// node wins it) and planted here for the approval callback to spend.
    async fn prepare(&self, seen: Seen) {
        let Some(store) = self.carried.store() else {
            return;
        };
        let Some(id) = seen.session else {
            return;
        };
        let Ok(Some(subject)) = store.session_subject(&id).await else {
            return;
        };
        self.sessions.hydrate(&id, &subject);
        let Some(key) = seen.staked_key else {
            return;
        };
        match store.spend(&id, &key).await {
            Ok(Some(approve)) => self.sessions.plant(&id, key, approve),
            Ok(None) => {}
            Err(e) => tracing::debug!(error = %e, "oauth_as: the consent answer could not be read"),
        }
    }

    pub(crate) fn identity(&self) -> &AsIdentity {
        &self.identity
    }

    pub(crate) fn server(&self) -> &Arc<AsServer> {
        &self.server
    }

    #[cfg(test)]
    pub(crate) fn sessions(&self) -> &Arc<super::consent::Sessions> {
        &self.sessions
    }
}

/// What [`AsPlane::prepare`] reads off a request, owned, so nothing borrowed from the request is
/// held across the store's awaits: the session the cookie names, and, on the authorization
/// endpoint, the key an answer to this exact request is staked under
/// ([`super::consent::request_key`] / [`super::consent::pushed_key`], as the approval callback
/// computes it).
struct Seen {
    session: Option<String>,
    staked_key: Option<String>,
}

impl Seen {
    fn of<B>(request: &http::Request<B>) -> Self {
        let session = super::consent::session_id(request.headers());
        let staked_key = request
            .uri()
            .path()
            .ends_with("/authorize")
            .then(|| {
                let pairs = request
                    .uri()
                    .query()
                    .map(super::routes::form_urlencoded_pairs)
                    .unwrap_or_default();
                let param = |name: &str| {
                    pairs
                        .iter()
                        .find(|(k, _)| k == name)
                        .map(|(_, v)| v.clone())
                };
                let client_id = param("client_id")?;
                Some(match param("request_uri") {
                    Some(handle) => super::consent::pushed_key(&client_id, &handle),
                    None => super::consent::request_key(
                        &client_id,
                        request.uri().path_and_query().map_or("", |p| p.as_str()),
                    ),
                })
            })
            .flatten();
        Self {
            session,
            staked_key,
        }
    }
}

/// A client's registered default scope, trimmed to what its registration allows: what `oauth-as`
/// grants a request naming no scope (its `AuthorizationServer::granted_default_scope`).
fn granted_default(client: &oauth_as::client::Client) -> oauth_as::scope::ScopeSet {
    oauth_as::scope::ScopeSet::from_tokens(
        client
            .default_scopes
            .iter()
            .map(|s| s.as_str())
            .filter(|s| client.allowed_scopes.contains(s)),
    )
    // Unreachable: every token here came out of a `ScopeSet` and so parsed once already.
    .unwrap_or_default()
}

/// `oauth_as.clients:` as `oauth-as` clients: confidential, authenticating with an RFC 7523
/// assertion against the configured PUBLIC keys — ES256 for EC keys, PS256 for RSA keys, one
/// algorithm per client (boot refuses a mix), for the authorization-code and refresh grants,
/// with the operator's `default_grant` as their whole scope (the same ceiling every other client
/// lands under). The keys were validated at boot (`AsIdentity::from_cfg`): EC P-256, no `d`.
fn provisioned_clients(identity: &AsIdentity) -> Vec<oauth_as::client::Client> {
    let ceiling = super::policy::default_grant_scopes(identity);
    identity
        .clients
        .iter()
        .map(|c| oauth_as::client::Client {
            client_id: oauth_as::client::ClientId::new(&c.client_id),
            auth: oauth_as::client::ClientAuth::ConfidentialAssertion {
                keys: oauth_as::client_assertion::AssertionKeys::PublicKeys {
                    alg: if c.jwks.keys.first().is_some_and(|k| k.kty == "RSA") {
                        oauth_as::jwt::JwsAlg::Ps256
                    } else {
                        oauth_as::jwt::JwsAlg::Es256
                    },
                    keys: c.jwks.keys.iter().map(public_jwk).collect(),
                },
            },
            grant_types: vec![
                oauth_as::grant::GrantType::AuthorizationCode,
                oauth_as::grant::GrantType::RefreshToken,
            ],
            redirect_uris: c.redirect_uris.clone(),
            allowed_scopes: ceiling.clone(),
            default_scopes: ceiling.clone(),
            name: Some(c.client_id.clone()),
            registration: None,
        })
        .collect()
}

/// One validated `oauth_as.clients:` key as `oauth-as`'s JWK. `AsIdentity::from_cfg` already
/// refused every shape but EC P-256 and RSA, so the members read here are present.
fn public_jwk(k: &crate::config::StaticClientJwk) -> oauth_as::jwt::Jwk {
    let member = |v: &Option<String>| v.clone().unwrap_or_default();
    if k.kty == "RSA" {
        oauth_as::jwt::Jwk::Rsa {
            n: member(&k.n),
            e: member(&k.e),
            kid: k.kid.clone(),
        }
    } else {
        oauth_as::jwt::Jwk::Ec {
            crv: oauth_as::jwt::EcCurve::P256,
            x: member(&k.x),
            y: member(&k.y),
            kid: k.kid.clone(),
        }
    }
}

/// THE FAPI 2.0 SECURITY PROFILE POSTURE, written onto a plain `ServerConfig`. The values are the
/// upstream `fapi2_conformance_server` example's, which is the configuration `oauth-as` 1.0.0 was
/// OpenID-certified under (FAPI2SP OP, private key + DPoP).
fn fapi2_posture(mut config: ServerConfig, identity: &AsIdentity) -> ServerConfig {
    // RFC 9126 PAR, MANDATORY (s5.3.2.2-3), with `redirect_uri` required in the push (s5.3.2.2-6).
    // The endpoint is set to the path `routes::mount` mounts, so the advertised document and the
    // served route cannot drift. The handle lifetime is `oauth-as`'s 60 s, under s5.3.2.2-12's 600.
    let mut par = oauth_as::par::ParConfig::new();
    par.pushed_authorization_request_endpoint = Some(identity.par_endpoint());
    par.require_pushed_authorization_requests = true;
    par.require_redirect_uri = true;
    config.par = Some(Box::new(par));
    // RFC 9449 on every token request: every token is sender-constrained (s5.3.4-2).
    config.require_dpop = true;
    config
        // s5.3.2.1-9 forbids refresh token rotation. Sound only because the line above binds every
        // token to its client's DPoP key; the plain posture keeps rotation and reuse detection.
        .with_refresh_rotation(RefreshRotation::Reuse)
        // s5.3.2.1-8 / s5.3.3.1-5: a client assertion's `aud` is the issuer, as a string.
        .with_assertion_audience(AssertionAudience::IssuerOnly)
        // s5.4.1: ES256 and PS256 only, for every JWS this server verifies or advertises.
        .with_jws_alg_allow_list(oauth_as::jwt::AlgAllowList::fapi())
}

/// THE PLAIN POSTURE'S RFC 8414 DOCUMENT: `oauth-as`'s own, less the members the FAPI 2.0
/// building blocks add to it at COMPILE time (`client_secret_jwt` and `private_key_jwt`, the
/// assertion and DPoP algorithm lists). Those three cargo features cannot be switched off at
/// runtime, and a deployment that did not ask for the profile must not advertise it: busbar's own
/// resource half answers `Bearer` only, so a client that read `dpop_signing_alg_values_supported`
/// and bound its token would be refused by the very plane the token is for. Serialized exactly as
/// `oauth-as` serializes its own (`serde_json::to_vec` of the same struct), so the bytes are the
/// document this posture always served — `signer_tests` pins them.
fn plain_metadata(server: &AsServer) -> bytes::Bytes {
    let mut meta = server.metadata();
    meta.token_endpoint_auth_methods_supported.retain(|m| {
        m != oauth_as::client_assertion::CLIENT_SECRET_JWT
            && m != oauth_as::client_assertion::PRIVATE_KEY_JWT
    });
    meta.token_endpoint_auth_signing_alg_values_supported = None;
    meta.dpop_signing_alg_values_supported = None;
    bytes::Bytes::from(
        serde_json::to_vec(&meta).expect("the RFC 8414 document is plain JSON and serializes"),
    )
}

/// THE SEAM-TYPED DPoP VERIFIER (`AsPlaneSeam::verify_dpop`): downcasts core's type-erased plane
/// and hands it to [`AsPlane::verify_dpop`]. A plane that is not this crate's verifies nothing.
pub(crate) fn seam_verify_dpop(
    plane: &Arc<dyn std::any::Any + Send + Sync>,
    presented: busbar_kernel::oauth_as::seam::DpopPresentation,
) -> std::pin::Pin<Box<dyn std::future::Future<Output = bool> + Send>> {
    let plane = Arc::clone(plane).downcast::<AsPlane>().ok();
    Box::pin(async move {
        match plane {
            Some(plane) => plane.verify_dpop(presented).await,
            None => false,
        }
    })
}

/// THE SEAM-TYPED BUILDER (`busbar_kernel::oauth_as::seam::AsPlaneSeam::build`): builds the plane AND
/// hands its sweeper to the kernel's clock — the whole "how do I come alive" act — and hands back
/// the type-erased object the kernel's `App::oauth_as` slot stores. This is the function pointer
/// [`crate::install`] registers; the kernel cannot call [`AsPlane::build_carrying`] directly, since
/// that would name this crate's type from `busbar-kernel`.
///
/// `prior` is the generation before this one (`None` at boot): the new server is built over what it
/// held ([`Carried`]), so a reload voids no token, client, session or replay-ledger entry.
pub(crate) fn seam_build<C: crate::Connections>(
    block: &serde_yaml::Value,
    secrets: Vec<(String, String)>,
    protected_resources: Vec<String>,
    prior: Option<&Arc<dyn std::any::Any + Send + Sync>>,
    store: Option<Arc<dyn busbar_contract::store_calls::StoreCalls>>,
) -> Result<Arc<dyn std::any::Any + Send + Sync>, String> {
    let identity = crate::config::identity_of(block)?;
    // The first generation decides where the records are kept; every later one carries them on.
    let carried = prior
        .and_then(|p| Arc::clone(p).downcast::<AsPlane>().ok())
        .map_or_else(
            || Arc::new(Carried::over(store)),
            |p| Arc::clone(&p.carried),
        );
    // The resolved signing-key material, handed back by the kernel under the path `check` reported
    // the reference at. None configured means an ephemeral key, and that is said at `warn`.
    let key_material = match identity.signing_key() {
        // Said once, when the key is generated: a later generation signs with the same one.
        None if carried.ephemeral_key.get().is_some() => None,
        // The deployment's store keeps the key: every node and every restart signs with the one
        // minted there. Said at `warn`, because whoever reads that store reads the key, and the
        // operator is the one who can keep it out (`super::shared`, module docs).
        None if carried.store().is_some() => {
            diag_warn!(
                OAUTH_AS_EPHEMERAL_SIGNING_KEY,
                "oauth_as: no signing_key configured; signing with the key minted once for the \
                 deployment and kept in its store, where whoever reads the store can read it, as \
                 they read the deployment keyset. Set `oauth_as.signing_key` (a secret reference) \
                 to keep the signing key out of the store."
            );
            None
        }
        None => {
            diag_warn!(
                OAUTH_AS_EPHEMERAL_SIGNING_KEY,
                "oauth_as: no signing_key configured, so an EPHEMERAL ES256 key was \
                 generated. Every token this deployment issues stops verifying when the \
                 process restarts. Set `oauth_as.signing_key` for anything but a trial."
            );
            None
        }
        Some(_) => Some(
            secrets
                .iter()
                .find(|(path, _)| path == crate::config::SIGNING_KEY_PATH)
                .map(|(_, value)| value.as_str())
                .ok_or_else(|| {
                    format!(
                        "{}: the reference was not resolved",
                        crate::config::SIGNING_KEY_PATH
                    )
                })?,
        ),
    };
    // The document fetch rides the composition root's connection table (`C`), read at fetch time.
    let fetch = Arc::new(super::cimd::ConnectorFetch { table: C::table });
    let mut plane =
        AsPlane::build_carrying(identity, key_material, protected_resources, fetch, carried)
            .map_err(|e| e.to_string())?;
    // `Storage::sweep_expired` is the only thing that reclaims anything in `oauth-as`, and it runs
    // when it is called and never otherwise. Handed to the kernel's clock here, once per
    // generation, and OWNED by the generation's server: a reload builds a new server with its own
    // sweeper, and letting the old generation go stops the old one ([`Sweeper`]), so a reload
    // leaves exactly one. Nothing is spawned: the sweep runs on the kernel's one clock.
    plane.sweeper = Some(sweep_on_clock(
        plane.server(),
        std::time::Duration::from_secs(60),
    ));
    Ok(Arc::new(plane) as Arc<dyn std::any::Any + Send + Sync>)
}

/// ONE SERVER'S SWEEPER, as its server holds it. Dropping it stops the sweep: the server owns its
/// sweeper, and the kernel's clock holds the sweep only weakly, so when a reload lets a
/// generation's server go, that generation's sweeper goes with it rather than holding the old
/// server alive and sweeping it forever.
pub(crate) struct Sweeper {
    /// The only strong holder of the sweep the kernel's clock beats.
    #[cfg_attr(not(test), allow(dead_code))]
    work: Arc<SweepWork>,
}

impl Sweeper {
    /// Whether the sweep is still on the clock (read by the reload test).
    #[cfg(test)]
    pub(crate) fn probe(&self) -> std::sync::Weak<SweepWork> {
        Arc::downgrade(&self.work)
    }
}

impl AsPlane {
    /// The unconfigured signing key this server signs with (PKCS#8 DER), when it has one.
    #[cfg(test)]
    pub(crate) fn unconfigured_key(&self) -> Option<Vec<u8>> {
        self.carried.ephemeral_key.get().cloned()
    }

    /// This server's sweeper, when it was built with one.
    #[cfg(test)]
    pub(crate) fn sweeper(&self) -> Option<&Sweeper> {
        self.sweeper.as_ref()
    }
}

/// SWEEP EXPIRED RECORDS, on the kernel's one clock, for as long as `server` is held.
///
/// `Storage::sweep_expired` is the ONLY thing that reclaims anything in `oauth-as`, and it runs when
/// it is called and never otherwise. Expiry is enforced on read, so an unswept deployment is not a
/// security hole — it is a memory one, and the endpoints that fill it take no credential, so an
/// unauthenticated caller sets the rate. A failure is logged and the sweep stays on the clock: a
/// sweeper that stops on the first transient error is a sweeper that is not running by the time
/// anyone looks.
///
/// The first sweep is due `every` after this call (sweeping an empty store at boot does nothing),
/// then every `every`. The work is handed to the kernel's clock ([`busbar_kernel::tick::on_clock`])
/// and holds the server WEAKLY: it never keeps a server alive, and it leaves the clock when the
/// [`Sweeper`] the caller keeps is dropped.
pub(crate) fn sweep_on_clock(server: &Arc<AsServer>, every: std::time::Duration) -> Sweeper {
    let work = Arc::new(SweepWork {
        server: Arc::downgrade(server),
        every,
        due: std::sync::Mutex::new(std::time::Instant::now() + every),
        sweeping: Arc::new(std::sync::atomic::AtomicBool::new(false)),
    });
    let on_clock: Arc<dyn busbar_kernel::tick::ClockWork> = Arc::<SweepWork>::clone(&work);
    busbar_kernel::tick::on_clock(Arc::downgrade(&on_clock));
    Sweeper { work }
}

/// The sweep as the kernel's clock beats it: due every `every`, one at a time.
pub(crate) struct SweepWork {
    server: std::sync::Weak<AsServer>,
    every: std::time::Duration,
    /// When the next sweep is due, on the monotonic clock.
    due: std::sync::Mutex<std::time::Instant>,
    /// A sweep is running: a beat that finds one still running starts no second.
    sweeping: Arc<std::sync::atomic::AtomicBool>,
}

impl busbar_kernel::tick::ClockWork for SweepWork {
    fn beat(&self, now: std::time::SystemTime) -> Option<busbar_kernel::tick::ClockJob> {
        use std::sync::atomic::Ordering;
        let server = self.server.upgrade()?;
        {
            let mut due = self
                .due
                .lock()
                .unwrap_or_else(std::sync::PoisonError::into_inner);
            let at = std::time::Instant::now();
            if at < *due || self.sweeping.swap(true, Ordering::AcqRel) {
                return None;
            }
            *due = at + self.every;
        }
        let sweeping = Arc::clone(&self.sweeping);
        Some(Box::pin(async move {
            sweep_once(&server, now).await;
            sweeping.store(false, Ordering::Release);
        }))
    }
}

/// One sweep of `server`'s expired records at wall time `now`.
async fn sweep_once(server: &AsServer, now: std::time::SystemTime) {
    // The trait must be in scope for the call; `Storage` is imported here rather than at the
    // module top so nothing else in this file can reach for a raw store operation.
    use oauth_as::store::Storage as _;
    // Warn-once transition latch: the sweep runs every beat it is due and a store fault persists,
    // so warn on the TRANSITION into the failing state and hold subsequent sweeps at debug. Reset
    // on any successful sweep so a future outage re-warns.
    static SWEEP_FAILED_WARNED: std::sync::atomic::AtomicBool =
        std::sync::atomic::AtomicBool::new(false);
    match server.store().sweep_expired(now).await {
        Ok(0) => {
            SWEEP_FAILED_WARNED.store(false, std::sync::atomic::Ordering::Relaxed);
        }
        Ok(n) => {
            SWEEP_FAILED_WARNED.store(false, std::sync::atomic::Ordering::Relaxed);
            tracing::debug!(reclaimed = n, "oauth_as: swept expired records");
        }
        Err(e) => {
            if !SWEEP_FAILED_WARNED.swap(true, std::sync::atomic::Ordering::Relaxed) {
                diag_warn!(
                    OAUTH_AS_SWEEP_FAILED,
                    error = %e,
                    "oauth_as: sweeping expired records failed; retrying on the next tick"
                );
            } else {
                diag_debug!(
                    OAUTH_AS_SWEEP_FAILED,
                    error = %e,
                    "oauth_as: sweeping expired records failed; retrying on the next tick"
                );
            }
        }
    }
}

