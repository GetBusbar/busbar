// THE BOTH-WAYS FIXTURE TABLES (test builds include them; nothing else reads them). Which in-tree
// plugin proves each kind both ways is DATA in `Cargo.toml`:
//
//   [package.metadata.busbar.both-ways]   <row> = "<logic crate>"
//
// This turns the rows into `$OUT_DIR/both_ways.rs`, which `src/tests/both_ways.rs` includes, so the
// conformance tests reach each fixture by its ROW and no test source names a plugin instance.
//
// Every kind is on the memory ABI with one door. A plugin repo is a LOGIC crate (its `door`, the
// LINKED door; no door symbol in its rlib) and the `-plugin` crate that packages it (its `cdylib`,
// the DROPPED-IN door, whose rlib exports `busbar_plugin_door` through `export_door!`). So a row
// names the logic crate, and this script derives the packaging crate's name from it and never
// links that crate: two exported doors in one fat-LTO unit are "symbol multiply defined". A row
// naming a `-plugin` crate is refused here.
//
// * `FIXTURES`: `(row, logic crate name, cdylib crate name)` of every packaged row (`PACKAGED_KINDS`);
// * `DOOR_FIXTURES`: `(row, cdylib crate name, linked door)` of each row whose linked door is its
//   logic crate's `door::door` (`DOOR_ROWS`);
// * the per-row alias `<row>_fixture`, the row's logic crate itself.
//
// The `store` row (`STORE_ROWS`) is also written to `$OUT_DIR/store_fixture.rs` (its crate alias and
// cdylib stem) and `$OUT_DIR/store_door.rs` (the store door example's one `export_door!` line), for
// the targets that cannot include `both_ways.rs`. The loader tests the axis, and a plugin tests
// itself. Reads only this crate's own manifest.

use std::env;
use std::path::PathBuf;

/// The kinds whose rows are packaged the plugin-repo way: the row names the logic crate (linked)
/// and the dropped-in `cdylib` is the same repo's `<logic crate>-plugin`. A row's kind is its key
/// up to the first `-` (`auth-verify` is a second proof of `auth`).
const PACKAGED_KINDS: &[&str] = &["auth", "export", "secret", "transport"];

/// The rows whose linked door is the logic crate's `door::door` (THE DESIGN, compiled-in =
/// dropped-in: the same door its dropped-in build exports), carried in `DOOR_FIXTURES`.
const DOOR_ROWS: &[&str] = &["auth", "auth-verify"];

/// The rows whose fixture is reached only by its crate alias, `store_fixture.rs` and its door example
/// (`store_door.rs`): the store kind's door is the crate's own `door`, not a `door::door`, and the
/// row is in no table.
const STORE_ROWS: &[&str] = &["store"];

/// The suffix of a plugin repo's packaging crate, in snake case.
const PACKAGING_SUFFIX: &str = "_plugin";

fn main() {
    println!("cargo:rerun-if-changed=Cargo.toml");
    // busbar-test-kit's source compiles into this crate's tests, and its unit tests run only here.
    println!("cargo::rustc-check-cfg=cfg(loader_self_tests)");
    println!("cargo::rustc-cfg=loader_self_tests");
    let manifest = std::fs::read_to_string("Cargo.toml").expect("read Cargo.toml");
    let mut out = String::from(
        "// @generated by build.rs from Cargo.toml `[package.metadata.busbar.both-ways]`.\n",
    );
    let mut crates = String::new();
    let mut fixtures = String::from(
        "/// `(row, logic crate name, cdylib crate name)` of each packaged both-ways row.\n\
         #[allow(dead_code)]\n\
         pub(crate) static FIXTURES: &[(&str, &str, &str)] = &[\n",
    );
    // THE STORE FIXTURE, BY KIND, for the targets that cannot include `both_ways.rs` (an integration
    // test, the store v3 door example): `store_fixture.rs` aliases the `store` row's crate and names
    // its cdylib stem; `store_door.rs` is the example's one `export_door!` line. No test or fixture
    // source names the store instance.
    let mut store_fixture = String::new();
    let mut store_door = String::new();
    let mut doors = String::from(
        "/// `(row, cdylib crate name, linked door)` of each both-ways row linked by its `door::door`.\n\
         pub(crate) static DOOR_FIXTURES: &[(&str, &str, busbar_contract::abi::mechanism::door::DoorFn)] = &[\n",
    );
    let mut in_table = false;
    for line in manifest.lines() {
        let code = line.split('#').next().unwrap_or("").trim();
        if code.starts_with('[') {
            in_table = code == "[package.metadata.busbar.both-ways]";
            continue;
        }
        if let (true, Some((row, krate))) = (in_table, code.split_once('=')) {
            let row = row.trim().trim_matches('"');
            let logic = krate.trim().trim_matches('"').replace('-', "_");
            if logic.ends_with(PACKAGING_SUFFIX) {
                panic!(
                    "Cargo.toml: both-ways row `{row}` names the packaging crate {logic}: name its \
                     logic crate. The packaging crate's rlib exports `busbar_plugin_door`, so the \
                     test binary must never link it; its cdylib name is derived from the row"
                );
            }
            let kind = row.split('-').next().unwrap_or(row);
            if STORE_ROWS.contains(&row) {
                // Reached by its crate alias and its door example below; no table row.
            } else if PACKAGED_KINDS.contains(&kind) {
                let cdylib = format!("{logic}{PACKAGING_SUFFIX}");
                fixtures.push_str(&format!("    (\"{row}\", \"{logic}\", \"{cdylib}\"),\n"));
                if DOOR_ROWS.contains(&row) {
                    doors.push_str(&format!(
                        "    (\"{row}\", \"{cdylib}\", ::{logic}::door::door),\n"
                    ));
                }
            } else {
                panic!(
                    "Cargo.toml: both-ways row `{row}` ({logic}) is of no known kind: add its kind \
                     to PACKAGED_KINDS or the row to STORE_ROWS"
                );
            }
            if row == "store" {
                store_fixture = format!(
                    "// @generated by build.rs from the `store` both-ways row.\n\
                     /// The `store` both-ways fixture crate, reached by kind.\n\
                     #[allow(unused_imports)]\n\
                     pub use ::{logic} as store_fixture;\n\
                     /// The file stem of its dropped-in `cdylib`.\n\
                     #[allow(dead_code)]\n\
                     pub const STORE_FIXTURE_CDYLIB: &str = \"{logic}\";\n"
                );
                store_door = format!(
                    "// @generated by build.rs from the `store` both-ways row.\n\
                     busbar_contract::export_door!(::{logic}::door);\n"
                );
            }
            // A second proof of one kind is keyed `<kind>-<proof>`; its alias is that key as an ident.
            let alias = row.replace('-', "_");
            crates.push_str(&format!(
                "// The `{row}` both-ways fixture crate.\n\
                 #[allow(unused_imports)]\n\
                 pub(crate) use ::{logic} as {alias}_fixture;\n"
            ));
        }
    }
    fixtures.push_str("];\n");
    out.push_str(&fixtures);
    doors.push_str("];\n");
    out.push_str(&doors);
    out.push_str(&crates);
    let dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(dir.join("both_ways.rs"), out).expect("write both_ways.rs");
    assert!(
        !store_fixture.is_empty(),
        "[package.metadata.busbar.both-ways] has no `store` row: the store fixture has no source"
    );
    std::fs::write(dir.join("store_fixture.rs"), store_fixture).expect("write store_fixture.rs");
    std::fs::write(dir.join("store_door.rs"), store_door).expect("write store_door.rs");
}
