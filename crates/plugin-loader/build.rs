// THE BOTH-WAYS FIXTURE TABLES (test builds include them; nothing else reads them). Which in-tree
// plugin proves each kind both ways is DATA in `Cargo.toml`:
//
//   [package.metadata.busbar.both-ways]   <kind> = "<fixture crate>"
//
// This turns the rows into `$OUT_DIR/both_ways.rs`, which `src/tests/both_ways.rs` includes, so the
// conformance tests reach each fixture by KIND and no test source names a plugin instance:
//
// * `HOT_FIXTURES`: `(kind, cdylib crate name)` of each HOT kind's row (a door or a `#[repr(C)]`
//   decl, `HOT_KINDS`), and for a `-plugin` row its logic crate's `linked` module as
//   `<kind>_linked`;
// * `DOOR_FIXTURES`: `(row, cdylib crate name, linked door)` of each memory-ABI row (`DOOR_ROWS`);
// * `EXPORT_FIXTURES`: `(row, logic crate name, cdylib crate name)` of each export sink row
//   (`EXPORT_KIND`): the row names the LOGIC crate (its `door`, linked) and the repo's `-plugin`
//   crate is its dropped-in `cdylib`;
// * the per-row alias `<kind>_fixture`, the fixture crate itself.
//
// The `store` row (`STORE_ROWS`) is also written to `$OUT_DIR/store_fixture.rs` (its crate alias and
// cdylib stem) and `$OUT_DIR/store_door.rs` (the store door example's one `export_door!` line), for
// the targets that cannot include `both_ways.rs`. The loader tests the axis, and a plugin tests
// itself (DECISIONS #2). Reads only this crate's own manifest.

use std::env;
use std::path::PathBuf;

/// The kinds whose fixture carries a door or a `#[repr(C)]` decl, not a cold entry (plane, transport
/// and the memory-ABI secret kind).
const HOT_KINDS: &[&str] = &["plane", "transport", "secret"];

/// The rows whose fixture is on its kind's MEMORY ABI: the linked door is the fixture's
/// `door::door` (THE DESIGN, compiled-in = dropped-in: the same door its dropped-in build exports),
/// not a cold entry.
const DOOR_ROWS: &[&str] = &["auth", "auth-verify"];

/// The rows whose fixture is reached only by its crate and its door example (`store_door.rs`): no
/// cold entry, no `door::door` (the store kind's door is the crate's own `door`).
const STORE_ROWS: &[&str] = &["store"];

/// The kind whose rows (`export`, `export-<proof>`) are sinks on the export kind's memory ABI: each
/// row names the sink's LOGIC crate (the linked `door`; no door symbol in its rlib), and its
/// dropped-in `cdylib` is that crate's `-plugin` twin from the same repo.
const EXPORT_KIND: &str = "export";

fn main() {
    println!("cargo:rerun-if-changed=Cargo.toml");
    let manifest = std::fs::read_to_string("Cargo.toml").expect("read Cargo.toml");
    let mut out = String::from(
        "// @generated by build.rs from Cargo.toml `[package.metadata.busbar.both-ways]`.\n",
    );
    let mut crates = String::new();
    // A HOT kind's row: its fixture has no cold entry — its linked door is its `#[repr(C)]` decl — so
    // it contributes its crate alias and its cdylib name only.
    let mut hot = String::from(
        "/// `(kind, cdylib crate name)` of each HOT kind's both-ways fixture.\n\
         #[allow(dead_code)]\n\
         pub(crate) static HOT_FIXTURES: &[(&str, &str)] = &[\n",
    );
    // THE STORE FIXTURE, BY KIND, for the targets that cannot include `both_ways.rs` (an integration
    // test, the store v3 door example): `store_fixture.rs` aliases the `store` row's crate and names
    // its cdylib stem; `store_door.rs` is the example's one `export_door!` line. No test or fixture
    // source names the store instance (instance-noun-neutrality, ARCHITECT Q-GG4(c)).
    let mut store_fixture = String::new();
    let mut store_door = String::new();
    // A memory-ABI row: its fixture's door.
    let mut doors = String::from(
        "/// `(row, cdylib crate name, linked door)` of each memory-ABI both-ways fixture.\n\
         pub(crate) static DOOR_FIXTURES: &[(&str, &str, busbar_contract::abi::sdk::door::MacroDoor)] = &[\n",
    );
    // An export sink row: its logic crate and its `-plugin` cdylib.
    let mut exports = String::from(
        "/// `(row, logic crate name, cdylib crate name)` of each export both-ways fixture.\n\
         #[allow(dead_code)]\n\
         pub(crate) static EXPORT_FIXTURES: &[(&str, &str, &str)] = &[\n",
    );
    let mut in_table = false;
    for line in manifest.lines() {
        let code = line.split('#').next().unwrap_or("").trim();
        if code.starts_with('[') {
            in_table = code == "[package.metadata.busbar.both-ways]";
            continue;
        }
        if let (true, Some((kind, krate))) = (in_table, code.split_once('=')) {
            let kind = kind.trim().trim_matches('"');
            let snake = krate.trim().trim_matches('"').replace('-', "_");
            if HOT_KINDS.contains(&kind) {
                hot.push_str(&format!("    (\"{kind}\", \"{snake}\"),\n"));
            } else if STORE_ROWS.contains(&kind) {
                // Reached by its crate alias and its door example below; no table row.
            } else if kind.split('-').next() == Some(EXPORT_KIND) {
                exports.push_str(&format!(
                    "    (\"{kind}\", \"{snake}\", \"{snake}_plugin\"),\n"
                ));
            } else if DOOR_ROWS.contains(&kind) {
                doors.push_str(&format!(
                    "    (\"{kind}\", \"{snake}\", ::{snake}::door::MACRO_DOOR),\n"
                ));
            } else {
                // The COLD/JSON lane is gone: every row is a door, a HOT decl, an export sink or
                // the store.
                panic!(
                    "Cargo.toml: both-ways row `{kind}` ({snake}) is on no door: add it to \
                     DOOR_ROWS, HOT_KINDS, STORE_ROWS or the EXPORT_KIND rows"
                );
            }
            if kind == "store" {
                store_fixture = format!(
                    "// @generated by build.rs from the `store` both-ways row.\n\
                     /// The `store` both-ways fixture crate, reached by kind.\n\
                     #[allow(unused_imports)]\n\
                     pub use ::{snake} as store_fixture;\n\
                     /// The file stem of its dropped-in `cdylib`.\n\
                     #[allow(dead_code)]\n\
                     pub const STORE_FIXTURE_CDYLIB: &str = \"{snake}\";\n"
                );
                store_door = format!(
                    "// @generated by build.rs from the `store` both-ways row.\n\
                     busbar_contract::export_door!(::{snake}::door);\n"
                );
            }
            // A second proof of one kind is keyed `<kind>-<proof>`; its alias is that key as an ident.
            // A HOT kind's `-plugin` row gets NO alias: nothing names its crate, so the test binary never
            // links its rlib. The row is a dev-dependency only so cargo BUILDS its cdylib, and a
            // `-plugin` crate's rlib exports `busbar_plugin_door` (`export_door!`), which two
            // doors in one fat-LTO unit make "symbol multiply defined". Naming the crate would link it.
            // A row naming the LOGIC crate (no `-plugin` suffix, so no door symbol in its rlib: the
            // `secret` row) is linked as an ordinary fixture crate below.
            if let (true, Some(logic)) = (HOT_KINDS.contains(&kind), snake.strip_suffix("_plugin"))
            {
                // The row's LOGIC crate (the same repo's crate the `-plugin` crate packs; it exports no
                // door symbol) gives the linked door: `<kind>_linked::{door, KEY}`.
                crates.push_str(&format!(
                    "#[allow(unused_imports)]\npub(crate) use ::{logic}::linked as {}_linked;\n",
                    kind.replace('-', "_")
                ));
                continue;
            }
            let alias = kind.replace('-', "_");
            crates.push_str(&format!(
                "// The `{kind}` both-ways fixture crate.\n\
                 #[allow(unused_imports)]\n\
                 pub(crate) use ::{snake} as {alias}_fixture;\n"
            ));
        }
    }
    hot.push_str("];\n");
    out.push_str(&hot);
    doors.push_str("];\n");
    out.push_str(&doors);
    exports.push_str("];\n");
    out.push_str(&exports);
    out.push_str(&crates);
    let dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(dir.join("both_ways.rs"), out).expect("write both_ways.rs");
    assert!(
        !store_fixture.is_empty(),
        "[package.metadata.busbar.both-ways] has no `store` row: the store fixture has no source"
    );
    std::fs::write(dir.join("store_fixture.rs"), store_fixture).expect("write store_fixture.rs");
    std::fs::write(dir.join("store_door.rs"), store_door).expect("write store_door.rs");
}
