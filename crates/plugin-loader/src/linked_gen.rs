// THE LINKED DOOR-ROOT TABLE'S GENERATOR (status row 195; coordinator ruling (a), BUSBAR-1.6.0.md
// l.272-274), shared VERBATIM between `build.rs` (which `include!`s this file and writes
// `$OUT_DIR/linked_doors.rs` with it) and `src/tests/linked_tests.rs` (which includes it to judge
// what it writes). Plain and dependency-free, because a build script has no dependencies to lean on.
//
// Which compiled-in crates are DOOR-ROOT is DATA in this crate's own manifest:
//
//   [package.metadata.busbar.door-root]   "<plugin crate>" = "<its door>"
//
// Each row's crate is an OPTIONAL dependency of this crate, behind the feature
// `linked-<plugin crate>` (the composition root forwards it: `busbar-plugin-loader/linked-<crate>`).
// The generated `linked_rows` admits each enabled row's door through `dispatch::load::open_linked`,
// the one `unsafe` entry, beside the dlopen call it shares its checks with; the root reaches the
// admitted doors only through `crate::linked`'s safe API and stays `forbid(unsafe_code)`.

/// The door-root table's header.
pub(crate) const DOOR_ROOT_TABLE: &str = "package.metadata.busbar.door-root";

/// The feature a door-root row's crate links under.
pub(crate) fn linked_feature(krate: &str) -> String {
    format!("linked-{krate}")
}

/// The `(crate, door)` rows of the door-root table, in manifest order (none when it has no table).
pub(crate) fn door_root_rows(manifest: &str) -> Vec<(String, String)> {
    let header = format!("[{DOOR_ROOT_TABLE}]");
    let mut in_table = false;
    let mut rows = Vec::new();
    for line in manifest.lines() {
        let code = line.split('#').next().unwrap_or("").trim();
        if code.starts_with('[') {
            in_table = code == header;
            continue;
        }
        if let (true, Some((k, v))) = (in_table, code.split_once('=')) {
            rows.push((
                k.trim().trim_matches('"').to_string(),
                v.trim().trim_matches('"').to_string(),
            ));
        }
    }
    rows
}

/// THE GENERATED SOURCE: `linked_rows`, every door-root row whose feature is on, its door admitted
/// through `open_linked`. Each row's crate must be an optional dependency of this crate behind its
/// `linked-<crate>` feature, and each `linked-*` feature must be a row: a row with no edge would
/// name a crate this build cannot link, and an edge with no row a crate linked past the table.
pub(crate) fn linked_doors_source(manifest: &str) -> String {
    let rows = door_root_rows(manifest);
    let features = section_keys(manifest, "features");
    let deps = section_lines(manifest, "dependencies");
    for (krate, door) in &rows {
        let feature = linked_feature(krate);
        assert!(
            features.contains(&feature),
            "Cargo.toml: door-root row `{krate}` has no `{feature}` feature"
        );
        assert!(
            deps.iter().any(|(k, spec)| k == krate
                && spec.replace(' ', "").contains("optional=true")),
            "Cargo.toml: door-root row `{krate}` is not an optional dependency of this crate"
        );
        let ident = krate.replace('-', "_");
        assert!(
            door.starts_with(&format!("{ident}::")),
            "Cargo.toml: door-root row `{krate}` names `{door}`, which is not in its crate"
        );
    }
    for feature in features.iter().filter(|f| f.starts_with("linked-")) {
        assert!(
            rows.iter().any(|(k, _)| linked_feature(k) == *feature),
            "Cargo.toml: feature `{feature}` links a crate the door-root table does not name"
        );
    }
    let mut out = String::from(
        "// @generated by build.rs from Cargo.toml `[package.metadata.busbar.door-root]` \
         (src/linked_gen.rs).\n\
         /// Every door-root crate this build links, `(crate, its door admitted)`, in table order: each\n\
         /// row's door, under its `linked-<crate>` feature, admitted by the one entry.\n\
         pub(crate) fn linked_rows() -> ::std::vec::Vec<(&'static str, ::std::result::Result<\
         crate::dispatch::LoadedDoor, crate::dispatch::LoadError>)> {\n    \
         let doors: &[(&'static str, ::busbar_contract::abi::mechanism::door::DoorFn)] = &[\n",
    );
    for (krate, door) in &rows {
        out.push_str(&format!(
            "        #[cfg(feature = {feature:?})]\n        ({krate:?}, ::{door}),\n",
            feature = linked_feature(krate)
        ));
    }
    out.push_str(
        "    ];\n    \
         doors\n        \
         .iter()\n        \
         .map(|(krate, door)| {\n            \
         // SAFETY: each `door` above is the door `plugin_door!` expanded in the crate beside it,\n            \
         // a crate the door-root table names and this build links behind its `linked-<crate>`\n            \
         // feature (`open_linked`'s contract).\n            \
         (*krate, unsafe { crate::dispatch::load::open_linked(*door) })\n        \
         })\n        \
         .collect()\n\
         }\n",
    );
    out.push_str("/// Every crate the door-root table names, linked in this build or not.\n");
    out.push_str("#[allow(dead_code)]\npub(crate) const DOOR_ROOT_CRATES: &[&str] = &[");
    for (krate, _) in &rows {
        out.push_str(&format!("{krate:?}, "));
    }
    out.push_str("];\n");
    out
}

/// The keys of the `[section]` table.
fn section_keys(manifest: &str, section: &str) -> Vec<String> {
    section_lines(manifest, section)
        .into_iter()
        .map(|(k, _)| k)
        .collect()
}

/// The `key = value` lines of the `[section]` table, both sides trimmed (the key unquoted).
fn section_lines(manifest: &str, section: &str) -> Vec<(String, String)> {
    let header = format!("[{section}]");
    let mut in_table = false;
    let mut out = Vec::new();
    for line in manifest.lines() {
        let code = line.split('#').next().unwrap_or("").trim();
        if code.starts_with('[') {
            in_table = code == header;
            continue;
        }
        if let (true, Some((k, v))) = (in_table, code.split_once('=')) {
            out.push((k.trim().trim_matches('"').to_string(), v.trim().to_string()));
        }
    }
    out
}
