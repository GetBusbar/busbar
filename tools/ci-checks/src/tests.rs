#[test]
fn seam_only_crypto_reached_around_the_seam_is_named_with_its_path() {
    assert_eq!(
        crypto_graph(LOCK),
        ["Cargo.lock: ring 0.17.14 is reachable outside busbar-crypto*: app -> reqwest -> rustls -> ring"]
    );
}

#[test]
fn seam_only_crypto_behind_the_seam_alone_is_clean() {
    let sealed = LOCK.replace(" \"reqwest\",\n", "");
    assert!(crypto_graph(&sealed).is_empty());
}
