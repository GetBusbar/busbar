/// `--filter` is record's flag; replay and diff select with `--id-filter`. Refused by name.
fn refuse_filter_flag(sub: &str) -> ! {
    eprintln!(
        "oracle: {sub} takes --id-filter <regex>; --filter is record's flag. Refusing: nothing was judged."
    );
    std::process::exit(2)
}

/// The value after `flag` (the last one), as the shell's `for a in "$@"; prev` loop reads it.
fn flag_value(args: &[String], flag: &str) -> String {
    let mut found = String::new();
    for pair in args.windows(2) {
        if pair[0] == flag {
            found.clone_from(&pair[1]);
        }
    }
    found
}

/// The dated family baselines' rows: `(family, version)`.
fn family_baseline_rows(data: &Path) -> Vec<(String, String)> {
    let Ok(text) = std::fs::read_to_string(data.join("family-baselines.tsv")) else {
        return Vec::new();
    };
    text.lines()
        .filter(|line| {
            let trimmed = line.trim_start();
            !trimmed.is_empty() && !trimmed.starts_with('#')
        })
        .filter_map(|line| {
            let (family, version) = line.split_once('\t')?;
            (!family.is_empty() && !version.is_empty())
                .then(|| (String::from(family), String::from(version)))
        })
        .collect()
}

/// A scratch path for a section's output when the replay named none.
fn fresh_out() -> PathBuf {
    TempDir::new(&temp_base(), "tmp.").map_or_else(|_| temp_base(), TempDir::keep)
}

/// The predev fences: cells recorded from a named predev build (no 1.5.5 baseline exists for them),
/// judged AFTER the 1.5.5 verdict, each against its own recording, under a separate heading. A
/// divergence is red. The exit is the worse of the two.
fn replay_fences(s: &Session, rc: i32, idf: &str, args: &[String]) -> i32 {
    let cand = flag_value(args, "--candidate");
    let out = flag_value(args, "--out");
    let fence = s.data.join("fence");
    let Ok(entries) = std::fs::read_dir(&fence) else {
        return rc;
    };
    let mut dirs: Vec<PathBuf> = entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.is_dir())
        .collect();
    dirs.sort();
    let mut worst = rc;
    for dir in dirs {
        let ledger = dir.join("ledger.tsv");
        if !ledger.is_file() {
            continue;
        }
        let ids = match ask_out(&["fence-filter", &path_text(&ledger)]) {
            Ok(text) => String::from(text.trim_end_matches('\n')),
            Err(code) => std::process::exit(i32::from(code)),
        };
        if !idf.is_empty() {
            let selected = oracle::compile_pattern(idf).is_some_and(|selector| {
                std::fs::read_to_string(&ledger).is_ok_and(|text| {
                    text.lines()
                        .filter(|line| !line.is_empty())
                        .filter_map(|line| line.split('\t').next())
                        .any(|id| selector.is_match(id))
                })
            });
            if !selected {
                continue;
            }
        }
        let name = dir
            .file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_default();
        println!();
        println!("== predev fence: {name} (recorded from a predev build; NOT 1.5.5 evidence) ==");
        let out_dir = if out.is_empty() {
            fresh_out()
        } else {
            PathBuf::from(&out)
        };
        let frc = s.judge(&strings(&[
            "diff",
            "--golden",
            &path_text(&dir),
            "--candidate",
            &cand,
            "--out",
            &path_text(&out_dir.join(format!("fence-{name}"))),
            "--cells",
            &path_text(&s.data.join("cells.json")),
            "--id-filter",
            &ids,
            "--strict",
        ]));
        worst = worst.max(frc);
    }
    worst
}

/// A family whose baseline is NOT 1.5.5 because 1.5.5 never served it (`family-baselines.tsv`),
/// judged against the dated baseline it names, by NAME, `--strict`, under its own heading.
fn replay_family_baselines(s: &Session, rc: i32, idf: &str, args: &[String]) -> i32 {
    let cand = flag_value(args, "--candidate");
    let out = flag_value(args, "--out");
    let accepted = flag_value(args, "--accepted");
    let mut worst = rc;
    for (family, version) in family_baseline_rows(&s.data) {
        if !idf.is_empty() && ask(&["family-selected", &path_text(&s.data), idf, &family]).code != 0
        {
            continue;
        }
        println!();
        println!(
            "== dated baseline: family {family} against golden/{version} (NOT 1.5.5 evidence) =="
        );
        let out_dir = if out.is_empty() {
            fresh_out()
        } else {
            PathBuf::from(&out)
        };
        let mut judge = strings(&[
            "diff",
            "--baseline-version",
            &version,
            "--candidate",
            &cand,
            "--out",
            &path_text(&out_dir.join(format!("baseline-{version}-{family}"))),
            "--cells",
            &path_text(&s.data.join("cells.json")),
        ]);
        if !accepted.is_empty() {
            judge.extend(strings(&["--accepted", &accepted]));
        }
        judge.extend(strings(&[
            "--family",
            &format!("^{}$", family.replace('.', "\\.")),
        ]));
        if !idf.is_empty() {
            judge.extend(strings(&["--id-filter", idf]));
        }
        judge.push(String::from("--strict"));
        let frc = s.judge(&judge);
        worst = worst.max(frc);
    }
    worst
}

/// A replay that judged nothing is not a verdict: the 1.5.5 section answers first and alone, an
/// argument refusal (2) stops the replay there, and a report that compared no owed cell is a
/// refusal (3). `Err(status)` is the replay's exit.
fn judged_or_refuse(rc: i32, args: &[String]) -> Result<(), i32> {
    if rc >= 2 {
        eprintln!(
            "oracle: the 1.5.5 replay refused (exit {rc}, above); nothing was judged, so no other section runs."
        );
        return Err(rc);
    }
    let out = flag_value(args, "--out");
    if out.is_empty() {
        return Ok(());
    }
    let report = format!("{out}/report.json");
    if ask(&["report-owed", &report]).code != 0 {
        return Err(3);
    }
    Ok(())
}

/// Split `--id-filter <regex>` out of a replay's or diff's arguments, refusing `--filter`.
fn split_id_filter(rest: &[String], sub: &str) -> (String, Vec<String>) {
    let mut idf = String::new();
    let mut args = Vec::new();
    let mut index = 0;
    while index < rest.len() {
        let arg = &rest[index];
        if arg == "--id-filter" {
            if let Some(value) = rest.get(index + 1) {
                idf.clone_from(value);
            }
            index += 2;
        } else if arg == "--filter" || arg.starts_with("--filter=") {
            refuse_filter_flag(sub);
        } else {
            args.push(arg.clone());
            index += 1;
        }
    }
    (idf, args)
}

/// Judge a filtered `diff`: the filter widened to its premise cells, the engine's output teed, and
/// whether no selected forgiveness was withheld (a withheld one is a refusal, 3). `extra` follows
/// the widened `--id-filter`.
fn filtered_diff(s: &Session, args: &[String], idf: &str, extra: &[String]) -> (i32, bool) {
    let Ok(wide) = widen_filter(&s.data, idf) else {
        std::process::exit(3)
    };
    let mut judge = vec![String::from("diff")];
    judge.extend(args.iter().cloned());
    judge.extend(strings(&["--id-filter", &wide]));
    judge.extend(extra.iter().cloned());
    let (rc, log) = s.judge_tee(&judge);
    let Ok(scratch) = TempDir::new(&temp_base(), "busbar-oracle-log.") else {
        std::process::exit(1)
    };
    let path = scratch.path().join("engine.log");
    let _ = std::fs::write(&path, log);
    (rc, withheld_selected(&s.data, &path, idf))
}

/// What a native recording needs of the run: the data, the product and the exports.
pub(crate) struct Recorder {
    pub(crate) data: PathBuf,
    pub(crate) product: PathBuf,
    pub(crate) envs: Vec<(String, String)>,
}

fn dispatch_replay(s: &Session, rest: &[String]) -> i32 {
    let (idf, mut args) = split_id_filter(rest, "replay");
    // UNDER MODERNCI THE 1.5.5 GOLDEN IS THE CONFIG'S TREE, READ FROM THE OBJECT DATABASE.
    if under_modernci() {
        let has_golden = args
            .iter()
            .any(|arg| arg == "--golden" || arg.starts_with("--golden="));
        if !has_golden {
            eprintln!(
                "oracle: a replay under ModernCI names its 1.5.5 golden with --golden; none was given. Refusing."
            );
            return 3;
        }
        if let Err(fail) = modernci_golden(&s.cfg.here, &s.cfg.cache_home, &mut args) {
            if !fail.message.is_empty() {
                eprintln!("{}", fail.message);
            }
            return 3;
        }
    }
    let cells = path_text(&s.data.join("cells.json"));
    if idf.is_empty() {
        let mut judge = vec![String::from("diff")];
        judge.extend(args.iter().cloned());
        judge.extend(strings(&["--cells", &cells]));
        let rc = s.judge(&judge);
        if let Err(code) = judged_or_refuse(rc, &args) {
            return code;
        }
        let frc = replay_fences(s, rc, "", &args);
        return replay_family_baselines(s, frc, "", &args);
    }
    // A filter that selects ONLY families with a dated baseline of their own owes the 1.5.5 section
    // nothing: its --strict would refuse "no owed cells matched", a red that judges nothing.
    let families: String = family_baseline_rows(&s.data)
        .iter()
        .map(|(family, _)| format!("{family} "))
        .collect();
    if ask(&["only-rebaselined", &path_text(&s.data), &idf, &families]).code == 0 {
        eprintln!(
            "oracle: the filter selects only families with a dated baseline (family-baselines.tsv); the 1.5.5 section is skipped"
        );
        return replay_family_baselines(s, 0, &idf, &args);
    }
    let (rc, withheld_ok) = filtered_diff(s, &args, &idf, &strings(&["--cells", &cells]));
    if let Err(code) = judged_or_refuse(rc, &args) {
        return code;
    }
    if !withheld_ok {
        return 3;
    }
    let frc = replay_fences(s, rc, &idf, &args);
    replay_family_baselines(s, frc, &idf, &args)
}

fn dispatch_diff(s: &Session, rest: &[String]) -> i32 {
    // The engine's own diff: a FILTERED one gets the same premise widening and refusal as replay.
    let (idf, mut args) = split_id_filter(rest, "diff");
    if under_modernci() {
        if let Err(fail) = modernci_golden(&s.cfg.here, &s.cfg.cache_home, &mut args) {
            if !fail.message.is_empty() {
                eprintln!("{}", fail.message);
            }
            return 3;
        }
    }
    if idf.is_empty() {
        let mut judge = vec![String::from("diff")];
        judge.extend(args);
        return s.judge(&judge);
    }
    let (rc, withheld_ok) = filtered_diff(s, &args, &idf, &[]);
    if !withheld_ok {
        return 3;
    }
    rc
}

/// The shim's `record`: `--bin B --plane P --out O [--filter F] [--prepared D]` onto the native
/// recorder, with `--out` honoured by being passed (`--out-dir`).
fn dispatch_record(s: &Session, rest: &[String]) -> i32 {
    let (mut bin, mut out, mut plane, mut filter, mut prepared) = (
        String::new(),
        String::new(),
        String::from("all"),
        String::new(),
        String::new(),
    );
    let mut index = 0;
    while index < rest.len() {
        let value = rest.get(index + 1).cloned().unwrap_or_default();
        match rest[index].as_str() {
            "--bin" => {
                bin = value;
                index += 2;
            }
            "--out" => {
                out = value;
                index += 2;
            }
            "--plane" => {
                plane = value;
                index += 2;
            }
            "--filter" => {
                filter = value;
                index += 2;
            }
            "--prepared" => {
                prepared = value;
                index += 2;
            }
            _ => index += 1,
        }
    }
    if bin.is_empty() || out.is_empty() {
        eprintln!("oracle record: need --bin and --out");
        return 2;
    }
    // A BOUND BAND NAMES ITS HOLDER: an explicitly chosen band is checked first, and the refusal
    // names each listener's pid and command line. An unset port is left to the recorder.
    let busy = bound_band_holders();
    if !busy.is_empty() {
        eprint!(
            "oracle record: the recording band is already bound, so nothing is recorded:\n{busy}Stop the stale process (kill <pid>) or choose a free ORACLE_LISTEN_PORT/ORACLE_ADMIN_PORT/ORACLE_MOCK_PORT.\n"
        );
        return 2;
    }
    s.verify_now();
    let recorder = Recorder {
        data: s.data.clone(),
        product: s.product.clone(),
        envs: s.envs.clone(),
    };
    record_native(&recorder, &s.bin, &bin, &out, &plane, &filter, &prepared)
}

/// Each listener on the explicitly chosen recording ports, as `  port P: pid N (command)` lines.
fn bound_band_holders() -> String {
    let mut busy = String::new();
    for name in [
        "ORACLE_LISTEN_PORT",
        "ORACLE_ADMIN_PORT",
        "ORACLE_MOCK_PORT",
    ] {
        let port = var(name);
        if port.is_empty() {
            continue;
        }
        let listeners = Command::new("lsof")
            .args(["-nP", "-t", &format!("-iTCP:{port}"), "-sTCP:LISTEN"])
            .stdin(Stdio::null())
            .stderr(Stdio::null())
            .output()
            .map(|output| String::from_utf8_lossy(&output.stdout).into_owned())
            .unwrap_or_default();
        let mut pids: Vec<&str> = listeners.lines().filter(|line| !line.is_empty()).collect();
        pids.sort_unstable();
        pids.dedup();
        for pid in pids {
            let command = Command::new("ps")
                .args(["-o", "command=", "-p", pid])
                .stdin(Stdio::null())
                .stderr(Stdio::null())
                .output()
                .map(|output| {
                    String::from_utf8_lossy(&output.stdout)
                        .trim_end()
                        .to_owned()
                })
                .unwrap_or_default();
            let command: String = command.chars().take(160).collect();
            busy.push_str(&format!("  port {port}: pid {pid} ({command})\n"));
        }
    }
    busy
}

/// `record --native` in a private TMPDIR: the judge (or its verifying wrapper `engine`) records the
/// candidate `bin` into `out`.
fn record_native(
    s: &Recorder,
    engine: &Path,
    bin: &str,
    out: &str,
    plane: &str,
    filter: &str,
    prepared: &str,
) -> i32 {
    let out_dir = absolute(Path::new(out));
    if let Err(error) = std::fs::create_dir_all(&out_dir) {
        eprintln!("oracle record: cannot make {}: {error}", out_dir.display());
        return 1;
    }
    let work = out_dir
        .parent()
        .map_or_else(|| out_dir.clone(), Path::to_path_buf);
    // A filtered recording carries the premise cells its forgivenesses probe.
    let filter = if filter.is_empty() {
        String::new()
    } else {
        match widen_filter(&s.data, filter) {
            Ok(wide) => wide,
            Err(_) => return 3,
        }
    };
    let mut command = Command::new(engine);
    command
        .args(["record", "--native", "--busbar-repo"])
        .arg(&s.product)
        .arg("--candidate-bin")
        .arg(bin)
        .arg("--oracle-data")
        .arg(&s.data)
        .arg("--work-dir")
        .arg(&work)
        .arg("--out-dir")
        .arg(&out_dir)
        .args(["--family", plane]);
    if !filter.is_empty() {
        command.args(["--filter", &filter]);
    }
    if !prepared.is_empty() {
        command.args(["--prepared", prepared]);
    }
    for (name, value) in &s.envs {
        command.env(name, value);
    }
    private_tmp(command)
}

/// The generated `record.sh`'s contract: `--bin B --out O [--filter F] [--plane P] [--shared-state]`.
pub(crate) fn record_sh(s: &Recorder, entry: &Path, rest: &[String]) -> i32 {
    let (mut bin, mut out, mut filter, mut plane) = (
        String::new(),
        String::new(),
        String::new(),
        String::from("all"),
    );
    let mut index = 0;
    while index < rest.len() {
        let value = rest.get(index + 1).cloned().unwrap_or_default();
        match rest[index].as_str() {
            "--bin" => {
                bin = value;
                index += 2;
            }
            "--out" => {
                out = value;
                index += 2;
            }
            "--filter" => {
                filter = value;
                index += 2;
            }
            "--plane" => {
                plane = value;
                index += 2;
            }
            _ => index += 1,
        }
    }
    if bin.is_empty() || out.is_empty() {
        eprintln!("record.sh(shim): need --bin and --out");
        return 2;
    }
    record_native(s, entry, &bin, &out, &plane, &filter, "")
}

/// Run one of the shim's own subcommands, or pass it to the judge.
pub(crate) fn dispatch(s: &Session, sub: &str, rest: &[String]) -> i32 {
    let data = path_text(&s.data);
    match sub {
        "tool-dir" => {
            println!("{}", s.tool_dir.display());
            0
        }
        // `cells --check` / `--selftest`: --cells defaults from the data dir.
        "cells" => {
            let mut args = vec![String::from("cells")];
            args.extend(rest.iter().cloned());
            if !rest.iter().any(|arg| arg == "--cells") {
                args.extend(strings(&[
                    "--cells",
                    &path_text(&s.data.join("cells.json")),
                ]));
            }
            s.judge(&args)
        }
        // The owed-baseline ratchet over the committed golden; under ModernCI the golden is the
        // config's tree from the object database, never the worktree.
        "replay-selftest" => {
            let mut args = strings(&[
                "--golden",
                &path_text(&s.data.join("golden/1.5.5")),
                "--baseline",
                &path_text(&s.data.join("owed-baseline.txt")),
            ]);
            args.extend(rest.iter().cloned());
            if under_modernci() {
                if let Err(fail) = modernci_golden(&s.cfg.here, &s.cfg.cache_home, &mut args) {
                    if !fail.message.is_empty() {
                        eprintln!("{}", fail.message);
                    }
                    return 3;
                }
            }
            let mut judge = vec![String::from("replay-selftest")];
            judge.extend(args);
            s.judge(&judge)
        }
        // The pinned engine's fetch-golden reads a tab-less comment line as the end of the data
        // (`pinned()` returns None from the whole function, exit 3), so it is fed a de-commented
        // copy of golden-digests.tsv until the parser is fixed upstream and re-pinned.
        "fetch-golden" => {
            let digests = s.data.join("golden-digests.tsv");
            let text = match std::fs::read_to_string(&digests) {
                Ok(text) => text,
                Err(error) => {
                    eprintln!("grep: {}: {error}", digests.display());
                    return 2;
                }
            };
            let clean: String = text
                .lines()
                .filter(|line| {
                    let trimmed = line.trim();
                    !trimmed.is_empty() && !trimmed.starts_with('#')
                })
                .map(|line| format!("{line}\n"))
                .collect();
            let clean_path = s.cfg.root.join("golden-digests.clean.tsv");
            if let Err(error) = std::fs::create_dir_all(&s.cfg.root)
                .and_then(|()| std::fs::write(&clean_path, clean))
            {
                eprintln!("oracle: cannot write {}: {error}", clean_path.display());
                return 1;
            }
            let mut args = strings(&[
                "fetch-golden",
                "--digests",
                &path_text(&clean_path),
                "--cache-dir",
                &path_text(&s.cache),
            ]);
            args.extend(rest.iter().cloned());
            s.judge(&args)
        }
        "fetch-plugin" => {
            let Some(name) = rest.first() else {
                eprintln!("oracle: fetch-plugin <name> [--check]");
                return 1;
            };
            let mut args = strings(&["fetch-plugin", name, "--data", &data]);
            args.extend(rest.iter().skip(1).cloned());
            s.judge(&args)
        }
        "record" => dispatch_record(s, rest),
        "replay" => dispatch_replay(s, rest),
        "diff" => dispatch_diff(s, rest),
        // normalize / merge / renormalize / harness-rev / selftest / ... pass through unchanged.
        _ => {
            let mut args = vec![String::from(sub)];
            args.extend(rest.iter().cloned());
            s.judge(&args)
        }
    }
}

/// The version's `<major>.<minor>` line (`sed -E 's/^([0-9]+)\.([0-9]+)\..*/\1.\2/'`).
fn line_of(version: &str) -> String {
    let mut parts = version.splitn(3, '.');
    match (parts.next(), parts.next(), parts.next()) {
        (Some(major), Some(minor), Some(_))
            if !major.is_empty()
                && !minor.is_empty()
                && major.bytes().all(|b| b.is_ascii_digit())
                && minor.bytes().all(|b| b.is_ascii_digit()) =>
        {
            format!("{major}.{minor}")
        }
        _ => String::from(version),
    }
}

fn epoch_secs() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_secs())
}

/// `[oracle-time]` lines: each phase since the start and since the last.
struct Clock {
    start: u64,
    last: u64,
}

impl Clock {
    fn new() -> Self {
        let now = epoch_secs();
        Self {
            start: now,
            last: now,
        }
    }

    fn ts(&mut self, phase: &str) {
        let now = epoch_secs();
        println!(
            "[oracle-time] {phase} +{}s ({}s)",
            now.saturating_sub(self.start),
            now.saturating_sub(self.last)
        );
        self.last = now;
    }
}

/// `source`-ing the store services' env file: its `export NAME=value` lines (bash `%q` quoted).
fn parse_exports(text: &str) -> Vec<(String, String)> {
    text.lines()
        .filter_map(|line| {
            let assignment = line.strip_prefix("export ")?;
            let (name, quoted) = assignment.split_once('=')?;
            let mut value = String::new();
            let mut chars = quoted.chars().peekable();
            while let Some(c) = chars.next() {
                match c {
                    '\\' => {
                        if let Some(next) = chars.next() {
                            value.push(next);
                        }
                    }
                    '\'' => {
                        for inner in chars.by_ref() {
                            if inner == '\'' {
                                break;
                            }
                            value.push(inner);
                        }
                    }
                    '"' => {
                        while let Some(inner) = chars.next() {
                            match inner {
                                '"' => break,
                                '\\' => {
                                    if let Some(next) = chars.next() {
                                        value.push(next);
                                    }
                                }
                                other => value.push(other),
                            }
                        }
                    }
                    other => value.push(other),
                }
            }
            Some((String::from(name), value))
        })
        .collect()
}

/// A TCP port nothing listens on, from 20000..40000.
fn free_port(salt: u64) -> u64 {
    let mut seed = epoch_secs() ^ (salt << 32) ^ u64::from(std::process::id());
    loop {
        seed = seed
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        let port = 20000 + (seed >> 33) % 20000;
        let Ok(port16) = u16::try_from(port) else {
            continue;
        };
        if std::net::TcpStream::connect_timeout(
            &std::net::SocketAddr::from(([127, 0, 0, 1], port16)),
            std::time::Duration::from_millis(200),
        )
        .is_err()
        {
            return port;
        }
    }
}

const STORE_SERVICES: &str = "testing/shadow-oracle/scripts/oracle-box-store-services.sh";

/// `bin/oracle ci-run`: what the ModernCI oracle check runs after its toolchain setup, whole or as
/// one shard. Judges exactly what the check's inline body judged: the judge from the config's pin,
/// the golden held add-only, the candidate recorded over the corpus (or this shard's share of it)
/// and replayed --strict against the 1.5.5 golden, the fences and the dated baselines. Each phase
/// prints `[oracle-time] <phase> +<since start>s (<in phase>s)`; the store backends start in the
/// background while the candidate builds, and only when the run selects a cell that needs one.
pub(crate) fn ci_run_command(here: &Path, rest: &[String]) -> i32 {
    let mut store_env: Option<Vec<(String, String)>> = None;
    let rc = ci_run_inner(here, rest, &mut store_env);
    if let Some(env) = store_env {
        let mut down = Command::new("bash");
        down.arg(here.join(STORE_SERVICES))
            .arg("down")
            .current_dir(here);
        for (name, value) in &env {
            down.env(name, value);
        }
        let _ = down.status();
    }
    rc
}

#[allow(clippy::too_many_lines)]
fn ci_run_inner(
    here: &Path,
    rest: &[String],
    store_env: &mut Option<Vec<(String, String)>>,
) -> i32 {
    // `ci-run --prepare <dir>`: only build what every shard records into <dir>, and stop.
    let mut prepare_out = String::new();
    if rest.first().map(String::as_str) == Some("--prepare") {
        let Some(dir) = rest.get(1) else {
            eprintln!("oracle: ci-run --prepare <dir>");
            return 1;
        };
        prepare_out.clone_from(dir);
    }
    let prepared = var("ORACLE_PREPARED_DIR");
    let mut clock = Clock::new();
    if std::env::set_current_dir(here).is_err() {
        eprintln!("oracle: cannot enter {}", here.display());
        return 1;
    }
    let cfg = match Cfg::from_env(here) {
        Ok(cfg) => cfg,
        Err(fail) => die(&fail),
    };
    // A refusal to judge (no judge configured) is infra, never red or green: exit 97.
    let mut session = match Session::open(cfg) {
        Ok(session) => session,
        Err(fail) => {
            if !fail.message.is_empty() {
                println!("{}", fail.message);
            }
            if fail.message.contains("NO JUDGE") {
                println!("modernci: infra: the oracle has no judge configured");
                return 97;
            }
            return 1;
        }
    };
    // The judge can prepare when it has the subcommand (busbar-release #445); a judge without it
    // cannot take a prepared candidate either, and a run that names one is refused, never degraded.
    if (!prepare_out.is_empty() || !prepared.is_empty())
        && dispatch_quiet(&session, "prepare", &strings(&["--help"])) != 0
    {
        eprintln!(
            "oracle ci-run: this judge has no `prepare` (busbar-release #445), so it cannot build or record a prepared candidate. Refusing: nothing was judged."
        );
        return 3;
    }
    if !prepared.is_empty() && !Path::new(&prepared).join("prepared.json").is_file() {
        eprintln!(
            "oracle ci-run: ORACLE_PREPARED_DIR={prepared} holds no prepared.json. Refusing: nothing was judged."
        );
        return 3;
    }
    // The add-only base: ORACLE_BASE_SHA (GitLab's core-oracle job), else ModernCI's MODERNCI_TO_SHA.
    let gbase = {
        let named = var("ORACLE_BASE_SHA");
        if named.is_empty() {
            var("MODERNCI_TO_SHA")
        } else {
            named
        }
    };
    let holds_golden = !gbase.is_empty()
        && Command::new("git")
            .args([
                "cat-file",
                "-e",
                &format!("{gbase}:testing/shadow-oracle/golden/1.5.5"),
            ])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .is_ok_and(|status| status.success());
    if holds_golden {
        let rc = dispatch(
            &session,
            "golden-guard",
            &strings(&["--repo", ".", "--base", &gbase, "--head", "HEAD"]),
        );
        if rc != 0 {
            return rc;
        }
    } else {
        println!(
            "golden-guard: the target ({}) holds no golden/1.5.5; nothing to hold add-only",
            if gbase.is_empty() { "none" } else { &gbase }
        );
    }
    clock.ts("judge+golden-guard");
    let shard = match shard_spec() {
        Ok(shard) => shard,
        Err(message) => {
            eprintln!("{message}");
            return 2;
        }
    };
    let data = session.data.clone();
    let data_text = path_text(&data);
    let mut filter = String::new();
    if let Some((k, n)) = shard {
        let (k_text, n_text) = (k.to_string(), n.to_string());
        filter = match ask_out(&["shard-filter", &data_text, &k_text, &n_text]) {
            Ok(text) => String::from(text.trim_end_matches('\n')),
            Err(_) => return 3,
        };
        let owned = ask_out(&["shard-ids", &data_text, &k_text, &n_text]).map_or(0, |text| {
            text.lines().filter(|line| !line.is_empty()).count()
        });
        println!(
            "oracle ci-run: shard {k} of {n} ({owned} of the corpus's cells, and the premise cells they probe)"
        );
    }
    let _ = std::fs::create_dir_all("target/oracle");
    // THE STORE BACKENDS, only for a run that selects a cell gated on one.
    let wide = if filter.is_empty() {
        String::new()
    } else {
        match oracle::answer(&strings(&["widen-filter", &data_text, &filter])) {
            Answer {
                code: 0, stdout, ..
            } => String::from(stdout.trim_end_matches('\n')),
            _ => return 3,
        }
    };
    let mut stores = match ask_out(&["needs-store", &data_text, &wide]) {
        Ok(text) => String::from(text.trim()),
        Err(_) => return 3,
    };
    if !prepare_out.is_empty() {
        stores = String::from("no");
    }
    let mut store_child = None;
    if stores == "yes" {
        let commit = {
            let named = var("MODERNCI_COMMIT");
            if named.is_empty() {
                let ci = var("CI_COMMIT_SHA");
                if ci.is_empty() {
                    String::from("local")
                } else {
                    ci
                }
            } else {
                named
            }
        };
        let suffix = format!(
            "{}-{}",
            commit.chars().take(12).collect::<String>(),
            std::process::id()
        );
        let env_file = here.join("target/oracle/store-services.env");
        let mut env = vec![
            (
                String::from("ORACLE_PG_NAME"),
                format!("oracle-store-postgres-{suffix}"),
            ),
            (
                String::from("ORACLE_MY_NAME"),
                format!("oracle-store-mysql-{suffix}"),
            ),
            (
                String::from("ORACLE_VK_NAME"),
                format!("oracle-store-valkey-{suffix}"),
            ),
            (String::from("ORACLE_PG_PORT"), free_port(1).to_string()),
            (String::from("ORACLE_MY_PORT"), free_port(2).to_string()),
            (String::from("ORACLE_VK_PORT"), free_port(3).to_string()),
            (String::from("ORACLE_STORE_ENV_FILE"), path_text(&env_file)),
        ];
        let _ = std::fs::remove_file(&env_file);
        *store_env = Some(env.clone());
        let log = std::fs::File::create(here.join("target/oracle/store-services.log"));
        let mut up = Command::new("bash");
        up.arg(STORE_SERVICES).arg("up").stdin(Stdio::null());
        for (name, value) in &env {
            up.env(name, value);
        }
        if let Ok(log) = log {
            if let Ok(again) = log.try_clone() {
                up.stdout(log).stderr(again);
            }
        }
        store_child = up.spawn().ok();
        session.envs.append(&mut env);
    } else {
        println!("oracle ci-run: no selected cell needs a store backend; none is started");
    }
    // THE BUILD. THE ONE BUILD: on a line whose plugins build from source (plugin-digests.tsv) the
    // recorder builds the candidate itself, with the run's throwaway release key, and reads `--bin`
    // for one thing only: `--version`, the release line. So `--bin` is a LINE PROBE that prints the
    // tree's own `busbar <version>`, and the recording is refused if the probe is what got recorded.
    // The release profile's LTO is thin with 16 codegen units for this check only.
    let lto = {
        let named = var("ORACLE_CI_LTO");
        if named.is_empty() {
            String::from("thin")
        } else {
            named
        }
    };
    let units = {
        let named = var("ORACLE_CI_CODEGEN_UNITS");
        if named.is_empty() {
            String::from("16")
        } else {
            named
        }
    };
    session
        .envs
        .push((String::from("CARGO_PROFILE_RELEASE_LTO"), lto));
    session
        .envs
        .push((String::from("CARGO_PROFILE_RELEASE_CODEGEN_UNITS"), units));
    let manifest = if Path::new("dist/default/Cargo.toml").is_file() {
        "dist/default/Cargo.toml"
    } else {
        "Cargo.toml"
    };
    let metadata = Command::new("cargo")
        .args([
            "metadata",
            "--locked",
            "--no-deps",
            "--format-version",
            "1",
            "--manifest-path",
            manifest,
        ])
        .envs(session.envs.iter().map(|(k, v)| (k, v)))
        .stdin(Stdio::null())
        .stderr(Stdio::inherit())
        .output();
    let metadata = match metadata {
        Ok(output) if output.status.success() => {
            String::from_utf8_lossy(&output.stdout).into_owned()
        }
        _ => return 3,
    };
    let version_answer = oracle::busbar_version(&metadata);
    eprint!("{}", version_answer.stderr);
    if version_answer.code != 0 {
        return 3;
    }
    let version = String::from(version_answer.stdout.trim());
    let line = line_of(&version);
    let builds = match ask_out(&["line-builds", &data_text, &line]) {
        Ok(text) => String::from(text.trim()),
        Err(_) => return 3,
    };
    let mut probe: Option<PathBuf> = None;
    let bin: String;
    if builds == "yes" {
        let probe_path = here.join("target/oracle/line-probe/busbar");
        if let Some(parent) = probe_path.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        let _ = std::fs::write(
            &probe_path,
            format!(
                "#!/bin/sh\n# bin/oracle ci-run LINE PROBE: answers --version for the tree under test; never a candidate.\necho \"busbar {version}\"\n"
            ),
        );
        let _ = make_executable(&probe_path);
        bin = path_text(&probe_path);
        println!(
            "oracle ci-run: line {line} builds its plugins from source, so the recorder builds the run-keyed candidate itself; --bin is the line probe (busbar {version})"
        );
        probe = Some(probe_path);
    } else {
        let mut build = Command::new("cargo");
        build.args(["build", "--locked", "--release"]);
        if manifest == "dist/default/Cargo.toml" {
            build.args([
                "--manifest-path",
                "dist/default/Cargo.toml",
                "--bin",
                "busbar",
                "--target-dir",
                "target",
            ]);
        } else {
            build.args(["-p", "busbar", "--bin", "busbar"]);
        }
        for (name, value) in &session.envs {
            build.env(name, value);
        }
        if !build.status().is_ok_and(|status| status.success()) {
            return 1;
        }
        bin = String::from("target/release/busbar");
    }
    clock.ts("build");
    if !prepare_out.is_empty() {
        let rc = dispatch(
            &session,
            "prepare",
            &strings(&[
                "--busbar-repo",
                &path_text(here),
                "--candidate-bin",
                &bin,
                "--out",
                &prepare_out,
            ]),
        );
        if rc != 0 {
            return 1;
        }
        clock.ts("prepare");
        return 0;
    }
    if dispatch(&session, "fetch-golden", &[]) != 0 {
        return 1;
    }
    clock.ts("fetch-golden");
    if let Some(mut child) = store_child {
        let env_file = session
            .envs
            .iter()
            .find(|(name, _)| name == "ORACLE_STORE_ENV_FILE")
            .map(|(_, value)| PathBuf::from(value))
            .unwrap_or_default();
        let log_path = here.join("target/oracle/store-services.log");
        let up = child.wait().is_ok_and(|status| status.success());
        let exports = std::fs::read_to_string(&env_file).unwrap_or_default();
        if !up || exports.is_empty() {
            print!("{}", std::fs::read_to_string(&log_path).unwrap_or_default());
            println!("oracle: the store backends did not come up");
            return 1;
        }
        for line in std::fs::read_to_string(&log_path)
            .unwrap_or_default()
            .lines()
        {
            if !line.starts_with("export ") {
                println!("{line}");
            }
        }
        session.envs.extend(parse_exports(&exports));
        clock.ts("stores");
    }
    if var("ORACLE_RECORD_WORKERS").is_empty() {
        let cpus = std::thread::available_parallelism()
            .map_or(4, std::num::NonZeroUsize::get)
            .max(4);
        session
            .envs
            .push((String::from("ORACLE_RECORD_WORKERS"), cpus.to_string()));
    }
    let workers = session
        .envs
        .iter()
        .rev()
        .find(|(name, _)| name == "ORACLE_RECORD_WORKERS")
        .map_or_else(|| var("ORACLE_RECORD_WORKERS"), |(_, value)| value.clone());
    println!("oracle ci-run: {workers} recording workers");
    let rec = "target/oracle/recordings/candidate";
    let rep = "target/oracle/reports/dev";
    let _ = std::fs::remove_dir_all(rec);
    let _ = std::fs::remove_dir_all(rep);
    let workers_dirs = |glob_name: &str| -> Vec<PathBuf> {
        std::fs::read_dir("target/oracle/recordings")
            .map(|entries| {
                entries
                    .filter_map(Result::ok)
                    .map(|entry| entry.path())
                    .filter(|path| {
                        path.file_name()
                            .is_some_and(|name| name.to_string_lossy().starts_with(glob_name))
                    })
                    .collect()
            })
            .unwrap_or_default()
    };
    for dir in workers_dirs("w") {
        let _ = std::fs::remove_dir_all(dir);
    }
    let mut record = strings(&["--bin", &bin, "--plane", "all", "--out", rec]);
    if !filter.is_empty() {
        record.extend(strings(&["--filter", &filter]));
    }
    if !prepared.is_empty() {
        record.extend(strings(&["--prepared", &prepared]));
    }
    let record_rc = dispatch(&session, "record", &record);
    if record_rc != 0 {
        return record_rc;
    }
    clock.ts("record");
    let mut done: Vec<PathBuf> = vec![PathBuf::from("target/oracle-candidate/release/busbar")];
    done.extend(
        workers_dirs("w")
            .into_iter()
            .map(|dir| dir.join("record.log")),
    );
    for file in done {
        if let Ok(modified) = std::fs::metadata(&file).and_then(|meta| meta.modified()) {
            let secs = modified
                .duration_since(std::time::UNIX_EPOCH)
                .map_or(0, |elapsed| elapsed.as_secs());
            println!(
                "[oracle-time]   {} done +{}s",
                file.display(),
                secs.saturating_sub(clock.start)
            );
        }
    }
    if let Some(probe) = &probe {
        let probe_sha = sha256_of(probe).unwrap_or_default();
        let meta = std::fs::read_to_string(Path::new(rec).join("meta.json"));
        if !meta.as_ref().is_ok_and(|text| !text.contains(&probe_sha)) {
            eprintln!(
                "oracle: the recording names the line probe as its binary (or wrote no meta.json): the recorder did not build its own candidate. Refusing: nothing was judged."
            );
            return 3;
        }
    }
    let mut replay = strings(&[
        "--golden",
        "testing/shadow-oracle/golden/1.5.5",
        "--candidate",
        rec,
        "--out",
        rep,
        "--strict",
    ]);
    if !filter.is_empty() {
        replay.extend(strings(&["--id-filter", &filter]));
    }
    let mut rc = dispatch(&session, "replay", &replay);
    clock.ts("replay");
    if let Some((k, n)) = shard {
        let (k_text, n_text) = (k.to_string(), n.to_string());
        if ask(&["shard-verify", &data_text, &k_text, &n_text, rep]).code != 0 && rc == 0 {
            rc = 1;
        }
        let _ = std::fs::write(
            Path::new(rep).join("shard.tsv"),
            format!("{k}\t{n}\t{rc}\n"),
        );
    }
    rc
}

/// A subcommand with its output discarded.
fn dispatch_quiet(session: &Session, sub: &str, rest: &[String]) -> i32 {
    session.verify_now();
    let mut args = vec![String::from(sub)];
    args.extend(rest.iter().cloned());
    session
        .command(&args)
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map_or(1, code_of)
}

/// The generated verifying wrapper: re-hash the judge against ModernCI's digest, then exec it.
fn judge_exec(rest: &[String]) -> i32 {
    let (Some(want), Some(bin)) = (rest.first(), rest.get(1)) else {
        eprintln!("oracle judge-exec: need <sha256> <judge> ...");
        return 2;
    };
    let got = sha256_of(Path::new(bin)).unwrap_or_default();
    if want.is_empty() || &got != want {
        eprintln!(
            "oracle: NO JUDGE: the judge at {bin} has sha256 '{got}' now, not ModernCI's '{want}'. Refusing."
        );
        return 1;
    }
    Command::new(bin)
        .args(&rest[2..])
        .status()
        .map_or(1, code_of)
}

fn exit_code(rc: i32) -> ExitCode {
    ExitCode::from(u8::try_from(rc & 0xff).unwrap_or(1))
}

/// `oracle run <sub> ...`: the shim's contract.
pub(crate) fn run(args: &[String]) -> ExitCode {
    let sub = args.first().map_or("", String::as_str);
    let rest = args.get(1..).unwrap_or_default();
    let here = match home() {
        Ok(here) => here,
        Err(fail) => die(&fail),
    };
    let data = cand_data(&here);
    let data_text = path_text(&data);
    let need = |usage: &str, count: usize| -> Vec<String> {
        if rest.len() < count {
            eprintln!("oracle: {usage}");
            std::process::exit(1);
        }
        rest.to_vec()
    };
    match sub {
        "record-sh" => {
            // Internal: the generated record.sh (`record-sh <judge entry> <record.sh args...>`).
            let Some(entry) = rest.first() else {
                eprintln!("record.sh(shim): no judge entry");
                return ExitCode::from(2);
            };
            let product = {
                let named = var("BUSBAR_ORACLE_PRODUCT_ROOT");
                if named.is_empty() {
                    here.clone()
                } else {
                    PathBuf::from(named)
                }
            };
            let recorder = Recorder {
                data: data.clone(),
                product,
                envs: Vec::new(),
            };
            return exit_code(record_sh(&recorder, Path::new(entry), &rest[1..]));
        }
        "judge-exec" => return exit_code(judge_exec(rest)),
        "premise-filter" => {
            let given = need("premise-filter <filter>", 1);
            return match widen_filter(&data, &given[0]) {
                Ok(wide) => {
                    println!("{wide}");
                    ExitCode::SUCCESS
                }
                Err(_) => ExitCode::from(3),
            };
        }
        "shard-ids" | "shard-filter" => {
            let given = need(&format!("{sub} <k> <n>"), 2);
            return exit_code(i32::from(
                ask(&[sub, &data_text, &given[0], &given[1]]).code,
            ));
        }
        "shard-cover" => {
            let given = need("shard-cover <n>", 1);
            return exit_code(i32::from(ask(&["shard-cover", &data_text, &given[0]]).code));
        }
        "shard-verify" => {
            let given = need("shard-verify <k> <n> <report-dir>", 3);
            return exit_code(i32::from(
                ask(&["shard-verify", &data_text, &given[0], &given[1], &given[2]]).code,
            ));
        }
        "shard-merge" => {
            let mut merge = vec![String::from("shard-merge"), data_text.clone()];
            merge.extend(rest.iter().cloned());
            let answer = oracle::answer(&merge);
            print!("{}", answer.stdout);
            eprint!("{}", answer.stderr);
            return exit_code(i32::from(answer.code));
        }
        "shard-spec" => {
            return match shard_spec() {
                Ok(Some((k, n))) => {
                    println!("{k} {n}");
                    ExitCode::SUCCESS
                }
                Ok(None) => ExitCode::SUCCESS,
                Err(message) => {
                    eprintln!("{message}");
                    ExitCode::from(2)
                }
            };
        }
        "ci-run" => return exit_code(ci_run_command(&here, rest)),
        "private-tmp" => {
            let Some((program, arguments)) = rest.split_first() else {
                return ExitCode::SUCCESS;
            };
            let mut command = Command::new(program);
            command.args(arguments);
            return exit_code(private_tmp(command));
        }
        "judge-pin" => {
            return match env_judge_pin() {
                Ok(text) => {
                    print!("{text}");
                    ExitCode::SUCCESS
                }
                Err(fail) => die(&fail),
            };
        }
        _ => {}
    }
    if let Some(rc) = crate::oracle_selftest::run(sub, rest, &here) {
        return exit_code(rc);
    }
    let session = match Cfg::from_env(&here).and_then(Session::open) {
        Ok(session) => session,
        Err(fail) => die(&fail),
    };
    exit_code(dispatch(&session, sub, rest))
}
