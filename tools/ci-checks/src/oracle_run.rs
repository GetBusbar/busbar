//! `oracle run <sub> ...`: what `bin/oracle` is (BLD-6: the shell file is a launcher of twenty lines
//! or fewer; this is its logic, in Rust). The argv contract is the shim's, unchanged: `cells`,
//! `record`, `replay`, `diff`, `normalize`, `merge`, `renormalize`, `harness-rev`, `fetch-golden`,
//! `fetch-plugin`, `replay-selftest`, `selftest`, `tool-dir`, and the shim's own: `ci-run`,
//! `premise-filter`, `shard-ids`, `shard-filter`, `shard-cover`, `shard-verify`, `shard-merge`,
//! `shard-spec`, `private-tmp`, `judge-pin`, and the selftests (`oracle_selftest.rs`).
//!
//! The launcher names the checkout in `BUSBAR_ORACLE_HOME`. The judge is `oracle_judge.rs`'s: found,
//! proven to be the pinned one, and re-hashed before every exec under ModernCI. A subcommand the
//! shim does not own is the judge's own and passes through.

use std::io::{Read as _, Write as _};
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode, Stdio};

use crate::oracle::{self, Answer};
use crate::oracle_judge::{
    cand_data, env_judge_pin, judge_want_var, make_executable, modernci_golden, resolve_bin,
    sha256_of, temp_base, under_modernci, var, Cfg, Fail, TempDir,
};

/// The judge's tool dir and the launch exports a run carries.
pub(crate) struct Session {
    pub(crate) cfg: Cfg,
    /// The judge binary.
    pub(crate) bin: PathBuf,
    /// Exports every child carries.
    pub(crate) envs: Vec<(String, String)>,
    /// `BUSBAR_ORACLE_DATA`.
    pub(crate) data: PathBuf,
    /// `BUSBAR_ORACLE_PRODUCT_ROOT`.
    pub(crate) product: PathBuf,
    /// `BUSBAR_ORACLE_TOOL_DIR`.
    pub(crate) tool_dir: PathBuf,
    /// The engine's cache.
    pub(crate) cache: PathBuf,
}

/// Say a refusal and leave with its status.
pub(crate) fn die(fail: &Fail) -> ! {
    if !fail.message.is_empty() {
        eprintln!("{}", fail.message);
    }
    std::process::exit(i32::from(fail.code))
}

/// A process exit status as the shell reads it.
pub(crate) fn code_of(status: std::process::ExitStatus) -> i32 {
    use std::os::unix::process::ExitStatusExt as _;
    status
        .code()
        .unwrap_or_else(|| 128 + status.signal().unwrap_or(0))
}

/// Single-quote `text` for a generated launcher.
fn sh_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "'\\''"))
}

/// The checkout the launcher names.
pub(crate) fn home() -> Result<PathBuf, Fail> {
    let named = var("BUSBAR_ORACLE_HOME");
    if named.is_empty() {
        return Err(Fail::new(
            2,
            "oracle: BUSBAR_ORACLE_HOME names no checkout; run this through bin/oracle",
        ));
    }
    Ok(PathBuf::from(named))
}

/// A path made absolute without resolving anything.
fn absolute(path: &Path) -> PathBuf {
    std::path::absolute(path).unwrap_or_else(|_| path.to_path_buf())
}

impl Session {
    /// Resolve the judge, write the tool dir (record.sh, the verifying wrapper, oracle-config.sh)
    /// and carry the tool-location and data contract.
    pub(crate) fn open(cfg: Cfg) -> Result<Self, Fail> {
        let bin = resolve_bin(&cfg)?;
        std::fs::create_dir_all(&cfg.shim_dir).map_err(|error| {
            Fail::new(
                1,
                format!("oracle: cannot make {}: {error}", cfg.shim_dir.display()),
            )
        })?;
        let exe = std::env::current_exe()
            .map_err(|error| Fail::new(1, format!("oracle: cannot name this program: {error}")))?;
        let exe_text = exe.to_string_lossy().into_owned();
        let here_text = cfg.here.to_string_lossy().into_owned();
        // JUDGE_ENTRY: what record.sh and the product scripts (BUSBAR_ORACLE_BIN) run. Under
        // ModernCI a wrapper that re-hashes the judge against the config's digest before each exec;
        // elsewhere the judge itself.
        let mut entry = bin.clone();
        if under_modernci() {
            entry = cfg.shim_dir.join("judge-verified");
            let want = var(&judge_want_var());
            write_launcher(
                &entry,
                &format!(
                    "#!/bin/sh\n# GENERATED by bin/oracle: the judge, re-verified against ModernCI's digest before every exec.\nexec {} oracle judge-exec {} {} \"$@\"\n",
                    sh_quote(&exe_text),
                    sh_quote(&want),
                    sh_quote(&bin.to_string_lossy()),
                ),
            )?;
        }
        // record.sh: HarnessOracle drives `$BUSBAR_ORACLE_TOOL_DIR/record.sh --bin <candidate> --out
        // <work>/candidate [--filter <F>]`; it is the native recorder under another name.
        write_launcher(
            &cfg.shim_dir.join("record.sh"),
            &format!(
                "#!/bin/sh\n# GENERATED by bin/oracle: forwards record.sh's contract to the native Rust recorder.\nBUSBAR_ORACLE_HOME={} exec {} oracle run record-sh {} \"$@\"\n",
                sh_quote(&here_text),
                sh_quote(&exe_text),
                sh_quote(&entry.to_string_lossy()),
            ),
        )?;
        let data = cand_data(&cfg.here);
        let product = {
            let named = var("BUSBAR_ORACLE_PRODUCT_ROOT");
            if named.is_empty() {
                cfg.here.clone()
            } else {
                PathBuf::from(named)
            }
        };
        let tool_dir = {
            let named = var("BUSBAR_ORACLE_TOOL_DIR");
            if named.is_empty() {
                cfg.shim_dir.clone()
            } else {
                PathBuf::from(named)
            }
        };
        let cache = {
            let named = var("BUSBAR_ORACLE_CACHE");
            if named.is_empty() {
                cfg.cache_home.join("busbar-oracle")
            } else {
                PathBuf::from(named)
            }
        };
        let envs = vec![
            (
                String::from("BUSBAR_ORACLE_TOOL_DIGEST"),
                format!("rust:{}@{}", cfg.release_repo, cfg.release_ref),
            ),
            (
                String::from("BUSBAR_ORACLE_PRODUCT_ROOT"),
                product.to_string_lossy().into_owned(),
            ),
            (
                String::from("BUSBAR_ORACLE_DATA"),
                data.to_string_lossy().into_owned(),
            ),
            (
                String::from("BUSBAR_ORACLE_TOOL_DIR"),
                tool_dir.to_string_lossy().into_owned(),
            ),
            (
                String::from("BUSBAR_ORACLE_BIN"),
                entry.to_string_lossy().into_owned(),
            ),
        ];
        let session = Self {
            cfg,
            bin,
            envs,
            data,
            product,
            tool_dir,
            cache,
        };
        // oracle-config.sh, materialized FROM THE ENGINE (it is embedded there): the config bytes
        // have exactly one source.
        let materialize = session.judge_quiet(&[
            String::from("tool-dir"),
            session.cfg.shim_dir.to_string_lossy().into_owned(),
            String::from("--materialize"),
        ]);
        if materialize != 0 {
            return Err(Fail::new(u8::try_from(materialize & 0xff).unwrap_or(1), ""));
        }
        Ok(session)
    }

    /// The judge is the file its digest names, now; under ModernCI anything else is NO JUDGE. The
    /// candidate's own code runs between the fetch and the judge's later runs, so a judge verified
    /// once could be swapped before the next exec.
    pub(crate) fn verify_now(&self) {
        if !under_modernci() {
            return;
        }
        let digest_var = judge_want_var();
        let want = var(&digest_var);
        let got = sha256_of(&self.bin).unwrap_or_default();
        if want.is_empty() {
            die(&Fail::new(
                1,
                format!(
                    "oracle: NO JUDGE: ModernCI's config sets no {digest_var} to verify the judge at {} against. Refusing.",
                    self.bin.display()
                ),
            ));
        }
        if got != want {
            die(&Fail::new(
                1,
                format!(
                    "oracle: NO JUDGE: the judge at {} has sha256 '{}' now, not ModernCI's {digest_var} ('{want}'): it changed after it was obtained. Refusing.",
                    self.bin.display(),
                    if got.is_empty() { "<unreadable>" } else { &got }
                ),
            ));
        }
    }

    fn command(&self, args: &[String]) -> Command {
        let mut command = Command::new(&self.bin);
        command.args(args);
        for (name, value) in &self.envs {
            command.env(name, value);
        }
        command
    }

    /// Run the judge (re-verified first) with our stdio; its exit status.
    pub(crate) fn judge(&self, args: &[String]) -> i32 {
        self.verify_now();
        self.command(args).status().map_or(1, code_of)
    }

    /// The judge with its stdout discarded.
    fn judge_quiet(&self, args: &[String]) -> i32 {
        self.verify_now();
        self.command(args)
            .stdout(Stdio::null())
            .status()
            .map_or(1, code_of)
    }

    /// The judge with stdout and stderr merged, echoed and returned (`2>&1 | tee`).
    fn judge_tee(&self, args: &[String]) -> (i32, String) {
        self.verify_now();
        let Ok((mut reader, writer)) = std::io::pipe() else {
            return (1, String::new());
        };
        let Ok(writer_again) = writer.try_clone() else {
            return (1, String::new());
        };
        let mut command = self.command(args);
        command.stdout(writer_again).stderr(writer);
        let Ok(mut child) = command.spawn() else {
            return (1, String::new());
        };
        drop(command);
        let mut seen = Vec::new();
        let mut chunk = [0u8; 8192];
        let stdout = std::io::stdout();
        while let Ok(count) = reader.read(&mut chunk) {
            if count == 0 {
                break;
            }
            seen.extend_from_slice(&chunk[..count]);
            let mut lock = stdout.lock();
            let _ = lock.write_all(&chunk[..count]);
            let _ = lock.flush();
        }
        let rc = child.wait().map_or(1, code_of);
        (rc, String::from_utf8_lossy(&seen).into_owned())
    }
}

/// Write a generated launcher and make it runnable.
fn write_launcher(path: &Path, text: &str) -> Result<(), Fail> {
    std::fs::write(path, text)
        .and_then(|()| make_executable(path))
        .map_err(|error| {
            Fail::new(
                1,
                format!("oracle: cannot write {}: {error}", path.display()),
            )
        })
}

fn strings(args: &[&str]) -> Vec<String> {
    args.iter().map(|arg| String::from(*arg)).collect()
}

/// The data logic's answer, its stdout and stderr passed through.
fn ask(args: &[&str]) -> Answer {
    let answer = oracle::answer(&strings(args));
    print!("{}", answer.stdout);
    eprint!("{}", answer.stderr);
    answer
}

/// The data logic's answer, its stdout returned (stderr passed through).
fn ask_out(args: &[&str]) -> Result<String, u8> {
    let answer = oracle::answer(&strings(args));
    eprint!("{}", answer.stderr);
    if answer.code == 0 {
        Ok(answer.stdout)
    } else {
        Err(answer.code)
    }
}

fn path_text(path: &Path) -> String {
    path.to_string_lossy().into_owned()
}

/// A filtered run carries its forgivenesses' premises: the filter widened to every premise cell of
/// every accepted difference whose cells it selects, or a refusal naming the cell.
pub(crate) fn widen_filter(data: &Path, filter: &str) -> Result<String, u8> {
    ask_out(&["widen-filter", &path_text(data), filter])
        .map(|text| String::from(text.trim_end_matches('\n')))
}

/// 3, naming each, when a forgiveness the filter selected was withheld over an unevaluable premise.
fn withheld_selected(data: &Path, log: &Path, filter: &str) -> bool {
    ask(&["withheld", &path_text(data), &path_text(log), filter]).code == 0
}

