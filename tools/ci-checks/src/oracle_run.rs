/// A sharded oracle check names its shard in the environment as `i/N`, i counted from 0:
/// `ORACLE_SHARD`, else `MODERNCI_SHARD`, else `MODERNCI_SHARD_INDEX` with `MODERNCI_SHARD_COUNT`.
/// The names are data (`ORACLE_SHARD_VARS`, `ORACLE_SHARD_INDEX_VAR`, `ORACLE_SHARD_COUNT_VAR`).
/// Answers `(k, n)` with k from 1, or nothing for an unsharded run (none set, or N = 1). Two
/// settings that disagree, or one that is not a shard, is a refusal.
pub(crate) fn shard_spec() -> Result<Option<(u64, u64)>, String> {
    let named = |name: &str, default: &str| {
        let value = var(name);
        if value.is_empty() {
            String::from(default)
        } else {
            value
        }
    };
    let mut found = String::new();
    for name in named("ORACLE_SHARD_VARS", "ORACLE_SHARD MODERNCI_SHARD").split_whitespace() {
        let value = var(name);
        if value.is_empty() {
            continue;
        }
        if !found.is_empty() && found != value {
            return Err(format!(
                "oracle: the shard is named twice and the names disagree ({found}, {name}={value}). Refusing."
            ));
        }
        found = value;
    }
    let index_var = named("ORACLE_SHARD_INDEX_VAR", "MODERNCI_SHARD_INDEX");
    let count_var = named("ORACLE_SHARD_COUNT_VAR", "MODERNCI_SHARD_COUNT");
    let (index, count) = (var(&index_var), var(&count_var));
    if !index.is_empty() || !count.is_empty() {
        let value = format!("{index}/{count}");
        if !found.is_empty() && found != value {
            return Err(format!(
                "oracle: the shard is named twice and the names disagree ({found}, {index_var}/{count_var}={value}). Refusing."
            ));
        }
        found = value;
    }
    if found.is_empty() {
        return Ok(None);
    }
    let not_i_of_n = || format!("oracle: the shard '{found}' is not i/N. Refusing.");
    let Some((i_text, n_text)) = found.split_once('/') else {
        return Err(not_i_of_n());
    };
    let digits = |text: &str| !text.is_empty() && text.bytes().all(|b| b.is_ascii_digit());
    if !digits(i_text) || !digits(n_text) {
        return Err(not_i_of_n());
    }
    let (Ok(i), Ok(n)) = (i_text.parse::<u64>(), n_text.parse::<u64>()) else {
        return Err(not_i_of_n());
    };
    if n < 1 || i >= n {
        return Err(format!(
            "oracle: the shard '{found}' is not a shard (0 <= i < N). Refusing."
        ));
    }
    Ok((n > 1).then_some((i + 1, n)))
}

// ---- a recording owns its temp directory ----------------------------------------------------------

/// Run `command` with `TMPDIR` at a fresh private directory, removed after, whatever the exit.
/// Every busbar the recorder boots sweeps `<TMPDIR>` at startup for plugin staging dirs a dead pid
/// left and prints a line when it finds any, so an inherited host `TMPDIR` made that line a function
/// of whatever else had crashed on the host.
pub(crate) fn private_tmp(mut command: Command) -> i32 {
    let Ok(dir) = TempDir::new(&temp_base(), "busbar-oracle-tmp.") else {
        eprintln!(
            "oracle: cannot make a private TMPDIR under {}",
            temp_base().display()
        );
        return 1;
    };
    command.env("TMPDIR", dir.path());
    command.status().map_or(1, code_of)
}

